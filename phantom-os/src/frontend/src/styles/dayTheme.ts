/**
 * Утиліти довільного кольору, які СПРАВДІ стоять у дереві.
 *
 * ── ЧОМУ СКАНУВАННЯ, А НЕ ДОБУТОК ────────────────────────────────────────
 *
 * До 17.09 блок дня був повним декартовим добутком: 138 кольорів × 9
 * властивостей × 5 станів = 6 210 перекриттів. Виміряно на опублікованому
 * бандлі (`dist-phone/assets/*.css`, збірка 12): Tailwind випустив рівно
 * **211** утиліт довільного кольору — рівно стільки, скільки літеральних
 * імен класів він знайшов у `content`. Решта 5 999 перекриттів цілили в
 * клас, якого в CSS немає взагалі: жоден елемент його не носить, бо сам
 * Tailwind його не породив. Це 96,6 % блоку, і це 9 477 рядків із 10 375 у
 * `messenger.css` — тобто майже весь шматок `MessengerLayout-*.css` на
 * 400 КБ, який телефон качав, щоб застосувати 211 правил.
 *
 * Тому джерело правди лишається те саме (мапа `NIGHT_TO_DAY` — вона й далі
 * каже, ЯКИЙ день відповідає ночі), а перелік того, ЩО емітувати, читається
 * звідти ж, звідки його читає Tailwind: з тексту дерева. Один сканер на
 * генератор і на сторожа, тож розійтись вони не можуть.
 *
 * ── МЕЖА ────────────────────────────────────────────────────────────────
 *
 * Сканер бачить лише ЛІТЕРАЛЬНІ імена класів — рівно те саме обмеження, що
 * й у Tailwind. Клас, склеєний із шматків (`bg-[${c}]`), Tailwind не
 * випускає, отже й перекривати нічого; перевірено 17.09 grep-ом по всьому
 * дереву — таких склейок немає жодної. Зʼявиться — утиліта не намалюється
 * і вночі, тож вада виявиться не тут.
 */
export function usedColourUtilities(root = 'src', extra: string[] = ['index.html']): Set<string> {
  let text = '';
  const walk = (dir: string): void => {
    for (const name of readdirSync(dir)) {
      const full = join(dir, name);
      if (statSync(full).isDirectory()) walk(full);
      else if (/\.(tsx?|jsx?)$/.test(name)) text += readFileSync(full, 'utf8');
    }
  };
  walk(root);
  for (const f of extra) if (existsSync(f)) text += readFileSync(f, 'utf8');

  const names = new Set<string>();
  const states = STATES.map((s) => s.name).filter(Boolean).join('|');
  const props = PROPS.map((p) => p.prefix).join('|');
  const re = new RegExp(
    `(?:^|[^-\\w:])((?:${states})?(?:${props})-(?:\\[#[0-9A-Fa-f]{6}\\]|white/\\d+))`,
    'g',
  );
  for (const m of text.matchAll(re)) {
    // Колір нормалізуємо у верхній регістр — мапа ключована саме так.
    names.add(m[1].replace(/#[0-9A-Fa-f]{6}/, (h) => h.toUpperCase()));
  }
  return names;
}

