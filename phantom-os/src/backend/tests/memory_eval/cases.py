from __future__ import annotations


def F(pred, value, text, source="owner_said", conf=0.95, subject="owner", kind="fact"):
    return {"kind": kind, "subject": subject, "predicate": pred, "value": value, "text": text,
            "source": source, "confidence": conf, "sensitivity": "normal"}


def say(text, *items, retract=()):
    return {"say": text, "extract": {"items": list(items), "retractions": list(retract)}}


def forget(fragment):
    return {"forget": fragment}


def case(cid, ctype, turns, ask, slot, expect=(), forbid=()):
    return {"id": cid, "type": ctype, "turns": turns, "ask": ask, "slot": list(slot),
            "expect": list(expect), "forbid": list(forbid)}


