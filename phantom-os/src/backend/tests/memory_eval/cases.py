# ── памʼять на двох вузлах: телефон ↔ ПК через журнал змін (SYNC.md) ──────────
# `on` — де прозвучала репліка (phone | pc); `sync()` — сеанс синку (телефон шле
# свої зміни, тоді забирає зміни ПК); `ask_on` — кого питають. Кожен випадок
# проганяє справжні правила обох вузлів: Kotlin-репліка телефона рахує те саме,
# що Python (спільні вектори `tests/vectors/memory_vectors.json`), тож телефон тут
# — другий `MemoryLedger` з пристроєм `phone-…`.


def on(node, turn):
    return {**turn, "on": node}


def sync():
    return {"sync": True}


def xcase(cid, ctype, turns, ask, slot, expect=(), forbid=(), ask_on="pc"):
    c = case(cid, ctype, turns, ask, slot, expect, forbid)
    c["ask_on"] = ask_on
    return c


