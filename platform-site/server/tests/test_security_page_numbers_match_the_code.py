"""Число на сторінці безпеки або дорівнює константі в коді, або його нема.

Сторінка безпеки — єдина, яку рецензент читає з дампом трафіку в руках, і саме
там кожне округлення коштує довіри до решти сторінок. Ціна вже плачена двічі:
строк життя сеансу спарування був утричі менший за написаний, а заголовок
дозволів давав рівно те, що сторінка називала забороненим.

Дві перевірки, і жодна не вірить копірайту на слово:
  1. ліміт запитів, названий словами, мусить накривати ВСІ ліміти сервера —
     сервер має два, і менший із них стояв на сторінці як єдиний;
  2. сторінка безпеки не сміє заперечувати факт, який сторінка завантажень
     показує кнопкою.
"""
import re
from pathlib import Path

SERVER_DIR = Path(__file__).resolve().parents[1]
SITE_DIR = SERVER_DIR.parent
SECURITY_COPY = SITE_DIR / "src/i18n/security.ts"
DOWNLOAD_COPY = SITE_DIR / "src/i18n/download.ts"
MAIN = SERVER_DIR / "main.py"

#: Як числа пишуться словами в обох мовах. Сторінка навмисно не показує цифр
#: у прозі, тож звіряти доводиться саме слова.
WORDS = {
    20: ("twenty", "двадцять", "20 requests/min", "20 запитів/хв"),
    120: ("hundred and twenty", "сто двадцять", "120/min", "120/хв"),
}


def _limits() -> dict[str, int]:
    """Ліміти, які сервер справді накладає."""
    text = MAIN.read_text(encoding="utf-8")
    out: dict[str, int] = {}
    for name in ("RATE_LIMIT", "RELAY_RATE_LIMIT"):
        m = re.search(rf"^{name}, {name[:-5]}WINDOW = (\d+), ([\d.]+)", text, re.M)
        if not m:
            m = re.search(rf"{name}[^=\n]*= *(\d+)", text)
        assert m, f"не знайшли {name} у main.py — перевірка міряє не те"
        out[name] = int(m.group(1))
    return out


def test_названий_ліміт_накриває_всі_ліміти_сервера():
    """Сервер має ДВА ліміти, а сторінка називала менший як єдиний.

    «Двадцять запитів на хвилину з адреси» — рецензент бере це за обіцянку,
    пише скрипт і дістає сто двадцять на `/relay/*`. Після цього він не вірить
    жодному числу на сторінці, і має рацію.

    Тут не вимагається називати обидва числа — вимагається, щоб найбільший
    ліміт сервера був НАЗВАНИЙ. Сховати можна лише те, чого немає.
    """
    limits = _limits()
    biggest = max(limits.values())
    copy = SECURITY_COPY.read_text(encoding="utf-8").lower()

    assert any(w in copy for w in WORDS[biggest]), (
        f"найбільший ліміт сервера — {biggest} за хвилину "
        f"({', '.join(f'{k}={v}' for k, v in limits.items())}), "
        f"а сторінка безпеки його не називає. Рецензент дістане {biggest} там, "
        "де їй обіцяли менше, і перестане вірити решті чисел"
    )


def test_сторінка_безпеки_не_заперечує_суму_яку_показує_сторінка_завантажень():
    """Дві сторінки за два кліки одна від одної не можуть казати протилежне.

    Картка збірки малює SHA-256 із кнопкою «копіювати», головна тримає рядок
    «підписана збірка й контрольна сума» у стовпці «Працює сьогодні», а
    сторінка безпеки казала «контрольної суми поруч ще немає». Заперечення
    власного продукту читається як недбалість там, де ми просимо довіри.
    """
    security = SECURITY_COPY.read_text(encoding="utf-8")
    download = DOWNLOAD_COPY.read_text(encoding="utf-8")

    # Сторінка завантажень СТВЕРДЖУЄ суму: мітка поля плюс текст перевірки.
    assert "sha: 'SHA-256'" in download or 'sha: "SHA-256"' in download, (
        "картка збірки більше не називає SHA-256 — перевірка міряє не те"
    )

    denials = [
        "no checksum next to it yet",
        "контрольної суми поруч ще немає",
    ]
    found = [d for d in denials if d in security]
    assert not found, (
        f"сторінка безпеки заперечує контрольну суму ({found}), "
        "а сторінка завантажень показує її кнопкою «копіювати». "
        "Одна з двох сторінок бреше, і рецензент знайде обидві за два кліки"
    )
