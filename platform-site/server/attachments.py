"""Вкладення месенджера у сховищі: межі числом і ключі, яким можна вірити.

Рішення власника 17.09 (`phantom-os-messenger/docs/BLOB_ATTACHMENTS_DECISION.md`):
дріт возить ПОСИЛАННЯ, а не байти. Відправник шифрує файл у себе, ллє
шифротекст прямо в R2 підписаним посиланням, а дротом їде кадр на кількасот
байтів — ключ об'єкта, sha256, розмір, ім'я, тип і ключ розшифрування.

Сервер шифротексту не читає: ключ розшифрування живе в наскрізно зашифрованому
кадрі й сюди не потрапляє НІКОЛИ. Те, що сервер таки бачить, — що об'єкт існує,
скільки важить і коли ліг, — названо вголос у документі рішення, а не сховане.

**Усі числа — тут.** Документ вимагає, щоб вони стояли в одному місці, а не
були розсіяні по коду; `main.py` і тести читають саме звідси.
"""
from __future__ import annotations

import secrets
from i18n import t


#: Куди лягають вкладення. Окремо від `builds/` НАВМИСНО і це не про охайність:
#: `builds/` роздається за ліцензійною політикою (`/api/download/link`), і
#: посилання на читання довільного ключа було б дірою в ній — будь-хто просив
#: би `builds/phantom-1.0.apk` через двері вкладень. Тому [is_object_key]
#: пускає лише цей префікс і лише намальовану тут форму.
OBJECT_PREFIX = "msgr/"

#: Скільки шістнадцяткових цифр в імені об'єкта. 32 цифри — 128 бітів із
#: `secrets`, як `PeerFile.BLOB_ID_CHARS` у телефоні. Ім'я НЕ несе ані розмови,
#: ані відправника: ключ об'єкта бачить сховище, а сховище не має дізнаватись,
#: хто з ким говорить.
OBJECT_ID_CHARS = 32

#: **Стеля одного об'єкта — 2 ГіБ.**
#:
#: Власник просив гігабайти, і це гігабайти. Число не кругле заради круглого:
#: вкладення кладеться ОДНИМ `PUT`, а в S3-протоколі, яким говорить R2, простий
#: `PUT` обмежений 5 ГіБ ([SINGLE_PUT_LIMIT_BYTES]). 2 ГіБ лишають запас, якого
#: вистачає і на 16 байтів тега AES-GCM, і на те, щоб підняти стелю ще раз, не
#: переписуючи спосіб завантаження на складений (multipart).
#:
#: Підняти вище за [SINGLE_PUT_LIMIT_BYTES] не можна доти, доки завантаження
#: одним запитом: тест тримає цю нерівність, щоб число не переросло спосіб.
MAX_OBJECT_BYTES = 2 * 1024 * 1024 * 1024

#: Межа ПРОТОКОЛУ, не наша. Простий `PUT` в S3 несе не більше 5 ГіБ; більший
#: об'єкт вимагає складеного завантаження, якого тут немає. Число стоїть поруч
#: зі стелею навмисно — щоб той, хто піднімає одну, побачив другу.
#:
#: ЧЕСНО: взято з опису протоколу, а не зміряно з цієї машини — ключів R2 тут
#: немає. Перший же файл понад 2 ГіБ перевірить це насправді.
SINGLE_PUT_LIMIT_BYTES = 5 * 1024 * 1024 * 1024

#: **Скільки живуть об'єкти — 30 діб.**
#:
#: Досить, щоб адресат, який поїхав на два тижні без мережі, застав свій файл;
#: і досить мало, щоб місце в бакеті не росло вічно. Відлік — від запису, не
#: від останнього читання: правило, яке продовжує життя об'єкта на кожне
#: відкриття, неможливо назвати людині одним числом.
OBJECT_TTL_DAYS = 30

#: **Чи це правило справді виконується.** False — і це не описка.
#:
#: Термін життя виконує ПРАВИЛО ЖИТТЄВОГО ЦИКЛУ бакета, яке ставиться в
#: Cloudflare, а не цим кодом. Поки його не поставлено, [OBJECT_TTL_DAYS] — це
#: оголошена політика, а не властивість сховища: об'єкти лежатимуть, доки їх
#: хтось не прибере руками.
#:
#: Прапорець стоїть тут, щоб жодне місце не показало людині «зберігається 30
#: діб» як доведений факт. Поставлять правило — тут стане True, і разом із цим
#: почервоніє тест, який зараз стереже саме теперішній стан.
LIFECYCLE_RULE_APPLIED = False

#: Скільки живе посилання на запис — 6 годин.
#:
#: Рахунок, а не смак: 2 ГіБ за 21 600 секунд — це 795 кбіт/с. Тобто стелю
#: встигає вивантажити навіть повільний домашній канал, а обрив на середині
#: лишає час перепочати. Та сама причина, що й у `storage.LINK_TTL_SECONDS`:
#: коротке посилання на важкий файл означає «з поганого зв'язку не можна
#: взагалі».
UPLOAD_LINK_TTL_SECONDS = 21_600

#: Стільки ж на читання, і з тієї самої арифметики: качати доводиться те саме.
DOWNLOAD_LINK_TTL_SECONDS = 21_600

_HEX = set("0123456789abcdef")


def new_object_key() -> str:
    """Ім'я, яке вигадує СЕРВЕР.

    Ключ ніколи не береться з рук клієнта, і це головне тут. Клієнтський ключ
    означав би дві діри одразу: чужий об'єкт можна було б перезаписати
    (`msgr/<чуже>`), а вийшовши префіксом — перезаписати ЗБІРКУ
    (`builds/phantom-1.0.apk`), яку сервер роздає за ліцензією. Тому форму
    задає цей рядок, а [is_object_key] пускає лише її.
    """
    return OBJECT_PREFIX + secrets.token_hex(OBJECT_ID_CHARS // 2)


def is_object_key(key: str) -> bool:
    """Чи це ключ, який видав [new_object_key], — і нічого іншого.

    Перевіряється ФОРМА, а не відсутність поганого: список заборонених рядків
    («..», «/», «builds») завжди коротший за фантазію того, хто пише запит.
    Тому дозволено рівно префікс плюс рівно [OBJECT_ID_CHARS] шістнадцяткових
    цифр у нижньому регістрі — ні скісної, ні крапки в такому рядку бути не
    може за побудовою.
    """
    if not isinstance(key, str) or not key.startswith(OBJECT_PREFIX):
        return False
    tail = key[len(OBJECT_PREFIX):]
    return len(tail) == OBJECT_ID_CHARS and all(c in _HEX for c in tail)


def refuse(size: int) -> str | None:
    """Чому цей файл не поїде сховищем, або None — поїде.

    Речення, а не код: його читає людина. Нуль теж відмова — об'єкт на нуль
    байтів це не файл, а слід невдалого шифрування, і краще спинити його тут,
    ніж дати адресатові порожнечу з правильним sha256.
    """
    if not isinstance(size, int) or isinstance(size, bool):
        return t("attachments.size_unknown")
    if size <= 0:
        return t("attachments.empty")
    if size > MAX_OBJECT_BYTES:
        gib = size / (1024 * 1024 * 1024)
        return t("attachments.too_big", gib=f"{gib:.2f}", cap=MAX_OBJECT_BYTES // (1024 * 1024 * 1024))
    return None


def keep_notice() -> dict[str, object]:
    """Те, що сервер зобов'язаний сказати про зберігання — разом із тим, чи це
    вже правда.

    `enforced=False` означає, що строк оголошений, але прибирання ще ніхто не
    ввімкнув. Поверхня, яка покаже «30 діб» і змовчить про це, збреше.
    """
    return {
        "keep_days": OBJECT_TTL_DAYS,
        "enforced": LIFECYCLE_RULE_APPLIED,
        "max_bytes": MAX_OBJECT_BYTES,
    }


# ── двері на КЛЮЧІ ПРИСТРОЮ, а не на акаунті ─────────────────────────────────
#
# Рішення власника 17.09. Три варіанти, і чому решта гірші:
#
# * Endpoint на вузлі месенджера означав би роздати ключі R2 кожному вузлу.
#   Виключено: ключ на пристрої — це ключ, який витік.
# * Акаунт platform-site означав би, що людина не може надіслати файл, доки не
#   заведе обліковку на сайті ліцензій. Це ДРУГА особа для того самого
#   продукту, а в месенджері особа вже Є — її ключ.
# * Отже: клієнт підписує запит своїм Ed25519 — тим самим, яким підписує все
#   інше, — сервер звіряє підпис і видає посилання. Жодного акаунта, ключі R2
#   лишаються на сервері.
#
# Звіряльник НЕ свій: `directory.verify` уже вміє рівно те кодування, яким
# підписує телефон (обидві абетки base64, з доповненням і без). Другий
# звіряльник того самого підпису розійшовся б із першим на першому ж уточненні
# формату — і розійшовся б мовчки.

import threading
import time

#: Наскільки може розійтися годинник пристрою з нашим. Поза цим вікном заява
#: не приймається: без межі підписаний запит жив би вічно й переграти його
#: можна було б через рік.
PROOF_SKEW_SECONDS = 120

#: Разове число заяви: 16 байтів шістнадцятково. Саме воно робить підпис
#: ОДНОРАЗОВИМ — той самий підпис удруге не проходить.
NONCE_CHARS = 32

#: **Скільки байтів на КЛЮЧ на добу — 20 ГіБ.**
#:
#: Тобто десять об'єктів на повній стелі. Людина, що шле десять
#: максимальних файлів на добу, — це вже надзвичайний випадок; ключ, що
#: просить більше, або зламаний, або зловживає. Обмеження саме НА КЛЮЧ, а не
#: на адресу: за одним NAT сидить ціле місто, а ключ — це пристрій.
#:
#: Облік чесний саме тому, що вага входить у підпис ([presign_put_sized]):
#: скільки клієнт НАЗВАВ, стільки й покладе, бо іншу вагу R2 відмовить. Тому
#: лічити оголошене — те саме, що лічити покладене.
DAILY_BYTES_PER_KEY = 20 * 1024 * 1024 * 1024

#: І скільки об'єктів — щоб ключ не намолотив мільйон посилань по байту.
DAILY_OBJECTS_PER_KEY = 200

#: Вікно обліку — доба.
QUOTA_WINDOW_SECONDS = 24 * 60 * 60

#: **Чи квота спільна для всього розгортання.** False — і це не описка.
#:
#: Лічильники живуть у пам'яті процесу: вони скидаються на кожне викладення й
#: НЕ спільні між примірниками сервера. Тобто це стеля проти випадкового
#: перевитрату й грубого зловживання, а не проти впертого зловмисника, який
#: чекає перезапуску. Щоб стало інакше, лічильник мусить лягти в базу — і тоді
#: тут стане True.
QUOTA_IS_SHARED = False

_lock = threading.Lock()
_seen_nonces: dict[str, float] = {}
_key_bytes: dict[str, list[tuple[float, int]]] = {}
_last_sweep = 0.0


def put_message(pub_key: str, size: int, nonce: str, issued_ms: int) -> bytes:
    """Речення, під яким стоїть підпис запиту на ЗАПИС.

    Поля з'єднані `|`, і жодне з них не може містити `|` за побудовою: ключ і
    підпис — base64, разове число — шістнадцяткове, решта — цифри. Тому
    речення однозначне, і два різні запити не можуть дати один рядок.

    Вага входить у підпис саме тут: інакше перехоплений запит можна було б
    переписати на 2 ГіБ і витратити чужу квоту.
    """
    return f"phantom-attachment-put|v1|{pub_key}|{size}|{nonce}|{issued_ms}".encode()


def get_message(pub_key: str, object_key: str, nonce: str, issued_ms: int) -> bytes:
    """Те саме для ЧИТАННЯ. Ключ об'єкта входить у підпис, тож посилання,
    виписане на один об'єкт, не перевикористати на інший."""
    return f"phantom-attachment-get|v1|{pub_key}|{object_key}|{nonce}|{issued_ms}".encode()


def _sweep(now: float) -> None:
    """Викидає разові числа й кошики, чиє вікно минуло. Під тим самим замком,
    що й видача квоти: прибирання між перевіркою й записом відкрило б ліміт."""
    global _last_sweep
    if now - _last_sweep < 60:
        return
    _last_sweep = now
    for nonce in [n for n, at in _seen_nonces.items() if now - at > PROOF_SKEW_SECONDS * 2]:
        del _seen_nonces[nonce]
    for key in list(_key_bytes):
        kept = [(at, n) for at, n in _key_bytes[key] if now - at <= QUOTA_WINDOW_SECONDS]
        if kept:
            _key_bytes[key] = kept
        else:
            del _key_bytes[key]


def is_fresh_nonce(nonce: str, issued_ms: int, now: float | None = None) -> str | None:
    """Чи ця заява свіжа й ще не бачена. Рядок — причина відмови, None — гаразд.

    Разове число ЗАПАМ'ЯТОВУЄТЬСЯ тут же, а не окремим викликом: між
    перевіркою й записом інший потік провів би той самий підпис удруге.
    """
    if not isinstance(nonce, str) or len(nonce) != NONCE_CHARS or not all(
        c in "0123456789abcdef" for c in nonce
    ):
        return t("attachments.nonce_missing")
    if not isinstance(issued_ms, int) or isinstance(issued_ms, bool) or issued_ms < 0 or issued_ms > 2**53:
        return t("api.stale_proof")
    wall = time.time() if now is None else now
    if abs(wall - issued_ms / 1000.0) > PROOF_SKEW_SECONDS:
        return t("api.stale_proof")
    with _lock:
        _sweep(wall)
        if nonce in _seen_nonces:
            return t("attachments.nonce_used")
        _seen_nonces[nonce] = wall
    return None


def charge(pub_key: str, size: int, now: float | None = None) -> str | None:
    """Списати вагу з добової квоти ключа. Рядок — відмова, None — списано.

    Перевірка й списання — одна дія під замком: два запити, що зайшли разом,
    інакше обидва побачили б місце й обидва його зайняли.
    """
    wall = time.time() if now is None else now
    with _lock:
        _sweep(wall)
        bucket = [
            (at, n) for at, n in _key_bytes.get(pub_key, []) if wall - at <= QUOTA_WINDOW_SECONDS
        ]
        used = sum(n for _, n in bucket)
        if len(bucket) >= DAILY_OBJECTS_PER_KEY:
            _key_bytes[pub_key] = bucket
            return t("attachments.quota_files", n=len(bucket), cap=DAILY_OBJECTS_PER_KEY)
        if used + size > DAILY_BYTES_PER_KEY:
            _key_bytes[pub_key] = bucket
            gib = DAILY_BYTES_PER_KEY // (1024 * 1024 * 1024)
            return t("attachments.quota_bytes", used=f"{used / (1024 ** 3):.1f}", cap=gib)
        bucket.append((wall, size))
        _key_bytes[pub_key] = bucket
    return None


def spent(pub_key: str, now: float | None = None) -> dict[str, int]:
    """Скільки цей ключ уже витратив — щоб людині можна було це показати."""
    wall = time.time() if now is None else now
    with _lock:
        bucket = [
            (at, n) for at, n in _key_bytes.get(pub_key, []) if wall - at <= QUOTA_WINDOW_SECONDS
        ]
    return {
        "objects": len(bucket),
        "bytes": sum(n for _, n in bucket),
        "daily_bytes": DAILY_BYTES_PER_KEY,
        "daily_objects": DAILY_OBJECTS_PER_KEY,
        "quota_shared": QUOTA_IS_SHARED,
    }


def reset_for_tests() -> None:
    """Лічильники — стан процесу; тест, що його не чистить, залежав би від
    порядку тестів."""
    global _last_sweep
    with _lock:
        _seen_nonces.clear()
        _key_bytes.clear()
        _last_sweep = 0.0


#: **Що сервер бачить, а чого не бачить — простими словами.**
#:
#: Власник звелів написати це людині там, де вона вмикає дорогу через сховище,
#: і не ховати під словом «безпечно». Текст живе ТУТ, а не в поверхні, щоб
#: чотири поверхні не розповідали про це чотирма різними способами.
def server_sees() -> dict[str, object]:
    return {
        "sees": [t(f"attachments.sees.{n}") for n in range(1, 5)],
        "does_not_see": [t(f"attachments.hidden.{n}") for n in range(1, 5)],
        "plain": t("attachments.plain"),
    }
