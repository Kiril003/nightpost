export const BLOCK_LABEL_KEYS = Object.keys(LABELS);

export function blockLabel(key: string, lang: Lang): string {
  if (key.startsWith('refused.')) {
    const r = REFUSALS[key.slice(8)];
    return r ? r[lang] : key;
  }
  return LABELS[key]?.[lang] ?? key;
}

