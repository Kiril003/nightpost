package local.phantom.companion.core.tool.permission

/**
 * ЯК саме виклик дістав дозвіл. Це і є відповідь на «за чиїм словом» у журналі:
 * без неї рядок каже, що інструмент спрацював, але не каже, чи його хтось
 * дозволяв.
 *
 * Значення збігаються зі словником стовпця `decision` у `tool_audit`.
 */
enum class ConsentPath(val wire: String) {
    /** Читання — згоди не потребує й не питалось. */
    READ("read"),

    /** Оператор відповів «цього разу». */
    ONCE("once"),

    /** Збережене «завжди» — не питали. */
    ALWAYS("always"),

    /** Оператор відповів «ніколи». */
    NEVER("never"),

    /** Відмовлено: заборона, або не було кому спитати. */
    DENIED("denied"),
}
