package local.phantom.companion.core.tool

/**
 * Наслідок виклику для людини, що тримає телефон. Окреме поле, а НЕ похідне від
 * [ToolPermission]: дозволи кажуть, чого інструмент торкається, ризик — чи мусить
 * оператор дізнатися про це до того, як воно станеться.
 *
 * Виміряно 12.09: 41 із 94 інструментів оголошували `permissions = emptySet()`,
 * серед них і ті, що діють. Виводити ризик із дозволів означало б сказати
 * «безпечно» про кожен такий.
 *
 * Значення за замовчуванням немає навмисно — компілятор змушує кожен новий
 * інструмент назвати свій ризик. Забутий `risk` не компілюється; забутий
 * `risk = READ` було б видно лише тоді, коли воно вже спрацювало.
 */
enum class ToolRisk {
    /**
     * Читає, рахує, малює на власному екрані або змінює власні дані застосунку
     * так, що це можна відкотити. Не питає.
     */
    READ,

    /**
     * Змінює стан пристрою ПОЗА застосунком: ліхтарик, гучність, яскравість,
     * «не турбувати», таймер, будильник, запуск чужого застосунку, сповіщення,
     * керування відтворенням, дії службою доступності. Питає.
     */
    DEVICE,

    /**
     * Виходить за межі пристрою або незворотне: лист людині, дзвінок, SMS,
     * запис у спільне сховище, shell, запис у мережу, видалення памʼяті
     * оператора. Питає.
     */
    OUTWARD,
    ;

    /** true для всього, що мусить дістати рішення оператора перед виконанням. */
    val needsConsent: Boolean get() = this != READ
}
