package local.phantom.companion.core.data.poi

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Пакет місць мусить памʼятати, куди він дивився.
 *
 * ЩО ЦЕ СТЕРЕЖЕ. `parse` читав `bbox` із файла й **викидав** його:
 * `OfflinePoiPack(doc.pois, doc.generated)`. Наслідок був тихий і дорогий —
 * за межами покриття пошук відповідав «нічого не знайдено», тобто робив
 * висновок ПРО МІСЦЕ там, де насправді не дивився. Для людини це два різні
 * світи: у першому їхати далі марно, у другому — треба завантажити пакет.
 *
 * Заміряно 31 серпня 2026 на асеті, що їде в застосунку: 21 335 місць,
 * bbox `[50.21, 30.24, 50.59, 30.83]` — Київ, 21 333 з 21 335 у місті.
 * Шлях `country/ua/` називає власника пакета, а не охоплення.
 */
class PackCoverageTest {

    private fun pack(bbox: String) = OfflinePoiPack.parse(
        """{"generated":7,"bbox":$bbox,"count":1,"pois":[
           {"id":1,"lat":50.45,"lon":30.52,"name":"тест","cat":"amenity","sub":"fuel"}]}""",
    )

    @Test
    fun `межі покриття доживають до читача`() {
        val p = pack("[50.21,30.24,50.59,30.83]")
        assertEquals(listOf(50.21, 30.24, 50.59, 30.83), p.bbox)
    }

    @Test
    fun `точка в межах — дивились`() {
        assertTrue(pack("[50.21,30.24,50.59,30.83]").covers(50.45, 30.52))
    }

    @Test
    fun `точка за межами — НЕ дивились, і це не те саме, що «нічого немає»`() {
        // Львів. Пакет про нього не знає нічого й не має права цього
        // приховувати за словом «не знайдено».
        assertFalse(pack("[50.21,30.24,50.59,30.83]").covers(49.84, 24.03))
    }

    @Test
    fun `пакет без оголошених меж покриває все`() {
        // Старі пакети про себе нічого не казали. Мовчання не має ставати
        // відмовою: інакше ліки вимкнули б пошук там, де він працював.
        assertTrue(pack("[]").covers(49.84, 24.03))
    }

    @Test
    fun `зіпсований пакет лишається порожнім, а не падає`() {
        val p = OfflinePoiPack.parse("{зовсім не json")
        assertEquals(0, p.size)
        assertTrue("порожній пакет не сміє звужувати покриття", p.covers(49.84, 24.03))
    }
}
