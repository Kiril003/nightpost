package local.phantom.companion.core.data.transit

/**
 * Звідки взялася ХВИЛИНА, яку бачить людина.
 *
 * Окремо від [TransitOrigin]: та відповідає за походження ПОЗИЦІЇ, і для
 * розкладу не має значення взагалі — статичний фід не знає, де зараз
 * автобус. Зліплені в один перелік, вони давали безглузді пари на кшталт
 * «розклад» у полі координат.
 *
 * Порядок оголошення — спадання довіри. Споживач, що не вміє показати
 * різницю, мусить показувати ГІРШИЙ стан, а не приховувати його.
 */
enum class TransitTimesOrigin {
    /** Живий фід сказав, що машина зараз тут. Єдине, що можна звати «live». */
    MEASURED,

    /** Опублікований розклад перевізника: конкретний рейс, конкретна хвилина. */
    SCHEDULED,

    /**
     * Похідна від інтервалу. Конкретної хвилини НЕМАЄ — є оцінка очікування
     * (див. [HeadwayWait]), і показувати її як час на годиннику заборонено.
     */
    MODELLED,
}
