package local.phantom.companion.core.data.transit

/**
 * Скільки насправді чекати, коли відомий лише інтервал.
 *
 * Половина інтервалу — неправда, і це не дрібниця. Пасажир приходить на
 * зупинку у випадковий момент, тож він потрапляє у ПРОМІЖОК, а довгі
 * проміжки ширші за короткі й ловлять більше людей (inspection paradox).
 * Середнє очікування — `E[H²] / 2E[H]`, що через коефіцієнт варіації `cv`
 * розкладається в `E[H] · (1 + cv²) / 2`.
 *
 * Для транспорту без диспетчера `cv ≈ 1` — і тоді чекати треба ЦІЛИЙ
 * інтервал, а не половину. OsmAnd ділить навпіл і систематично обіцяє
 * менше, ніж буде; помилка завжди в бік «встигнеш», тобто робить людину
 * пізньою. Тут помилка має бути в інший бік.
 */
object HeadwayWait {

    /**
     * Вуличний транспорт без диспетчерського регулювання: автобус,
     * тролейбус, трамвай у загальному потоці. Скупчення пар («bus
     * bunching») робить розподіл проміжків близьким до показникового.
     */
    const val CV_UNDISPATCHED = 1.0

    /**
     * Метро й лінії з живим регулюванням: інтервал тримають, і розкид
     * лишається малим.
     */
    const val CV_DISPATCHED = 0.3

    /**
     * @param headwaySec середній інтервал між машинами.
     * @param cv коефіцієнт варіації проміжків. 0 — ідеальний такт
     *   (`H/2`), 1 — жодного регулювання (`H`).
     */
    fun expectedWaitSec(headwaySec: Int, cv: Double = CV_UNDISPATCHED): Int {
        if (headwaySec <= 0) return 0
        val safeCv = cv.coerceIn(0.0, 2.0)
        return (headwaySec * (1.0 + safeCv * safeCv) / 2.0).toInt().coerceAtLeast(1)
    }

    /** Те саме у хвилинах, округлено ВГОРУ — недооцінка тут і є вадою. */
    fun expectedWaitMinutes(headwaySec: Int, cv: Double = CV_UNDISPATCHED): Int {
        val sec = expectedWaitSec(headwaySec, cv)
        return if (sec <= 0) 0 else (sec + 59) / 60
    }
}
