package local.phantom.companion.core.data

/**
 * Чи піднялась рідна бібліотека SQLCipher у цьому процесі.
 *
 * Навіщо окремо: профіль малював пігулку «СХОВИЩЕ · SQLCipher» безумовним
 * літералом, тобто назву шифру у формі стану, який не міг почервоніти ніколи.
 * А завантаження бібліотеки — `runCatching { System.loadLibrary("sqlcipher") }`
 * з `onFailure { Log.e(…) }` — падає ТИХО: у журнал, повз екран. Пігулка мала
 * одне джерело, і то не те.
 *
 * [nativeLoaded] і виконує спробу, і є її відповіддю, тож розійтись їм нема як.
 * `System.loadLibrary` ідемпотентний, а `by lazy` лишає рівно одну спробу на
 * процес — тож будь-хто може спитати, не платячи за це другим завантаженням і
 * не міняючи порядку відкриття бази.
 *
 * Чого це НЕ каже: що база на диску справді зашифрована. Це доводиться на
 * пристрої, а не звідси. Тут відповідь вужча й чесна — чи є в процесі те, чим
 * шифрувати.
 */
object VaultCrypto {
    val nativeLoaded: Boolean by lazy {
        runCatching { System.loadLibrary("sqlcipher") }.isSuccess
    }
}
