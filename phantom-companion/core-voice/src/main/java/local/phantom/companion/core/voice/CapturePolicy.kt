package local.phantom.companion.core.voice

/**
 * Джерела запису, у порядку, в якому їх варто пробувати.
 *
 * Android дає їх під різні задачі, і різниця не в назві: за кожним стоїть
 * власний ланцюжок обробки, який ОС чіпляє ще до того, як байти дійдуть до
 * нас.
 */
enum class CaptureSource { VoiceRecognition, VoiceCommunication, Mic }

/**
 * Яким має бути вхід мікрофона — залежно від того, говорить PHANTOM чи ні.
 *
 * ## Чому це не одна константа
 *
 * `VOICE_COMMUNICATION` — тракт телефонії: ОС чіпляє до нього придушення
 * ехо, придушення шуму й **автоматичне регулювання підсилення**. Перше в
 * дуплексі несуче: без нього власний голос PHANTOM'а з динаміка вертається
 * у мікрофон, VAD бачить мовлення й PHANTOM перебиває сам себе.
 *
 * Але поза дуплексом платити за це нема за що, а рахунок реальний. Модель
 * Vosk рахує i-вектор (`ivector/final.ie`, `online_cmvn.conf`) — оцінку
 * каналу й голосу зі СТАЦІОНАРНОЇ статистики сигналу. AGC змінює
 * підсилення в часі, тобто робить цю статистику нестаціонарною, і оцінка
 * виходить неправильною; придушення шуму на додачу вирізає зі спектра саме
 * ту тиху високочастотну деталь, якою відрізняються приголосні. Обидва
 * блоки — не з того розподілу, на якому модель училась. Тракт, який Android
 * тримає саме для розпізнавання, — `VOICE_RECOGNITION`; ним же відкриває
 * мікрофон і власний Android-демо-сервіс Vosk.
 *
 * Тож правило одне: **дуплекс отримує тракт телефонії, бо йому потрібне
 * придушення ехо; одиночний запис отримує тракт розпізнавання й більше
 * нічого.** MIC лишається останнім запасним варіантом — деякі OEM просто
 * відмовляють у виборі, і напівдуплексний мікрофон незрівнянно кращий за
 * жоден.
 *
 * Чистий Kotlin: рішення видно на JVM, без пристрою.
 */
object CapturePolicy {

    fun sources(duplex: Boolean): List<CaptureSource> = if (duplex) {
        listOf(CaptureSource.VoiceCommunication, CaptureSource.VoiceRecognition, CaptureSource.Mic)
    } else {
        listOf(CaptureSource.VoiceRecognition, CaptureSource.Mic)
    }

    /**
     * Придушувач ехо має сенс лише тоді, коли є що придушувати. Поза
     * дуплексом він нічого не скасовує — а [VoiceController.echoCancelled]
     * звітував би «так» і вводив в оману тих, хто це читає.
     */
    fun cancelEcho(duplex: Boolean): Boolean = duplex

    /** Придушення шуму — ефект того самого тракту телефонії. Див. вище. */
    fun suppressNoise(duplex: Boolean): Boolean = duplex
}
