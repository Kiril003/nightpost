package local.phantom.companion.core.voice.supertonic

/**
 * Голоси, якими PHANTOM уміє говорити.
 *
 * Supertonic 3 везе десять стилів (F1-F5 / M1-M5), а до 01.09 у каталозі
 * моделей був жорстко прописаний рівно один — `voice_styles/M1.json`. Тобто
 * девʼять голосів існували, були оплачені вагою рушія і **недосяжні**: вибору
 * не було ніде, бо вибирати не було з чого — на диск приїжджав один файл.
 */
enum class VoiceStyle(
    /** Імʼя у сховищі Supertonic — воно ж імʼя файла на диску. */
    val id: String,
    /** Як це називається людині. Без «F1»: людина обирає голос, не індекс. */
    val label: String,
) {
    F1("F1", "Жіночий · тепліший"),
    F2("F2", "Жіночий · рівний"),
    F3("F3", "Жіночий · нижчий"),
    F4("F4", "Жіночий · світліший"),
    F5("F5", "Жіночий · мʼякший"),
    M1("M1", "Чоловічий · рівний"),
    M2("M2", "Чоловічий · нижчий"),
    M3("M3", "Чоловічий · твердіший"),
    M4("M4", "Чоловічий · тепліший"),
    M5("M5", "Чоловічий · світліший");

    /** Файл, у який цей стиль лягає поруч із рушієм. */
    val fileName: String get() = "voice_$id.json"

    companion object {
        /**
         * Що звучало до появи вибору. Лишається стандартом навмисно: людина,
         * яка нічого не обирала, мусить і далі чути той самий голос, що вчора.
         */
        val DEFAULT = M1

        fun byId(id: String?): VoiceStyle = entries.firstOrNull { it.id == id } ?: DEFAULT

        /**
         * **Підписи — не описи звуку, а орієнтири.** Вони складені з назв
         * стилів, а не з прослуховування: жодна людина в цьому домі їх не
         * чула, і чесно сказати, чим «твердіший» відрізняється від «рівного»,
         * ми зараз не можемо. Тому в інтерфейсі поруч мусить бути кнопка
         * послухати — підпис лише звужує пошук, а вирішує вухо.
         */
        const val LABELS_ARE_GUESSES = true
    }
}
