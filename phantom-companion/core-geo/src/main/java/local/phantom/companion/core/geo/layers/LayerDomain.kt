package local.phantom.companion.core.geo.layers

/**
 * 12-доменне дерево контенту карти: ДЕ шар живе, коли оператор його шукає.
 * Ортогонально до [LayerTheme] (спосіб оновлення/кешування — властивість
 * того, ЯК шар живе, а не ПРО ЩО він). Замінює накопичувальні звалища за
 * країною джерела чи механізмом оновлення («ukraine», «live») угрупованням
 * за предметом — повний розбір трьох відхилених альтернатив (питання,
 * свіжість, регістр) — у ia-map-structure.md §1.
 *
 * Не кожен шар має домен: базова підкладка й растри-підложжя (Overture
 * base, DEM, населення) — полотно, на якому контент домену малюється, а не
 * контент, до якого гортають; їхній [GeoLayerSpec.domain] лишається null,
 * як і «Домен 0» у PC-реєстрі.
 */
enum class LayerDomain(val title: String) {
    /** Тривоги (згасають) і зони, що лишаються — небезпека, яку не проминути. */
    DANGER("Небезпека"),

    /** «Чи проїду / де небезпечно йти» — перешкоди рельєфу й маршруту. */
    MOVEMENT_TERRAIN("Рух і місцевість"),
    MEDICAL_EVAC("Медицина та евакуація"),
    PROTECTED_SITES("Захищені та цивільні обʼєкти"),
    LOGISTICS_BORDERS("Логістика та кордони"),
    ADMIN_SERVICES("Адміністрація та побут"),
    INFRASTRUCTURE("Інфраструктура"),

    /** Впізнаваність / цифрова експозиція — камери, Wi-Fi, стільникові вежі. */
    SIGNALS_SURVEILLANCE("Сигнали та стеження"),
    SKY_TIME("Небо і час"),
    ENVIRONMENT("Довкілля"),

    /** Власні збережені дані оператора — нотатки, присутність, розвідка. */
    PERSONAL("Моє"),
    REFERENCE("Довідка"),
}
