package local.phantom.companion.core.geo.sky

/**
 * Під яким світлом людина зараз стоїть — чотирма іменами замість `Boolean`.
 *
 * ПОРОГИ (висота сонця над пласким відкритим обрієм):
 *
 * | фаза     | смуга              | земля   | чому саме тут                       |
 * |----------|--------------------|---------|-------------------------------------|
 * | `DAY`    | вище +6°           | день    | тіні короткі, колір землі не має значення |
 * | `GOLDEN` | −5°..+6°           | день    | сонце низько: довгі тіні, блиск в очі — але це ще ДЕНЬ |
 * | `DUSK`   | −12°..−5°          | сутінки | сонце зайшло, світло пішло          |
 * | `NIGHT`  | нижче −12°         | ніч     | EENT: темно для неозброєного ока    |
 *
 * −5° — це НЕ цивільні сутінки (−6°, [SolarAlmanac.CIVIL_DEG]), і різниця
 * навмисна. Астрономічний поріг тут не потрібен: потрібен той, на якому скрим
 * уже досить щільний, щоб сховати одноразове перевантаження стилю. −5° виміряли
 * саме так, і на ньому мапа темніє сьогодні — цей вал не має права зсунути час,
 * коли земля темніє, бо власник уже ловив нас на протилежному («мапа швидко
 * темною стає», 16.08). Цивільні сутінки лежать усередині смуги `DUSK` і
 * лишаються порогом там, де важлива астрономія, а не перефарбування:
 * [UsableLight] рахує придатне світло саме до −6°.
 *
 * `GOLDEN` — не привід темніти. Золоту годину несе скрим, який тепліє
 * безперервно від +10° і не коштує жодного перевантаження стилю; земля під ним
 * лишається денною, поки сонце справді не зайде.
 */
enum class SkyPhase {
    DAY,
    GOLDEN,
    DUSK,
    NIGHT,
    ;

    /** Полярність для тих, кому справді треба два стани, а не чотири. */
    val dark: Boolean get() = this == DUSK || this == NIGHT
}

/**
 * Сонце в одному значенні: де воно, і що це значить.
 *
 * @property morning схід чи захід — сонце піднімається. Світанок тонується
 *   холоднішим за вечір, і без цієї ознаки обидві смуги −5°..+6° однакові.
 */
data class SkyFix(
    val elevationDeg: Double,
    /** За годинниковою стрілкою від істинної півночі. 180° = південь. */
    val azimuthDeg: Double,
    val phase: SkyPhase,
    val morning: Boolean,
) {
    val dark: Boolean get() = phase.dark
}
