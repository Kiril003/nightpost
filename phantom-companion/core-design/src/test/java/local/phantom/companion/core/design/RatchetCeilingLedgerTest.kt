        val verdict = drift(c, "    private val radiusBudget = 66")
        assertTrue(
            "перейменування мусить давати явне «не знайдено», а не мовчазний зелений",
            verdict != null && verdict.contains("не знайдено"),
        )
    }

    /** Контроль на самого себе: незмінене джерело мусить давати `null`, інакше тест вище зелений завжди. */
    @Test
    fun `незмінена стеля не рахується розходженням`() {
        val c = ledger.first { it.name == "rawMotionCeiling" }
        assertNull(drift(c, "    private val rawMotionCeiling = 2"))
    }

    /**
     * Стелю не піднімають «тимчасово».
     *
     * Саме так вартові гинуть найчастіше: число росте на одиницю з коментарем
     * «поки що», коміт проходить рецензію як дрібниця, і причина зникає разом
     * із памʼяттю автора. Якщо підняття справді потрібне — воно потрібне
     * назавжди або не потрібне взагалі.
     */
    @Test
    fun `стелю не піднімають з відмовкою`() {
        val root = repoRoot()
        val guilty = mutableListOf<String>()
        for (c in ledger) {
            val lines = File(root, c.path).readLines()
            val at = lines.indexOfFirst { it.contains("private val ${c.name}") }
            if (at < 0) continue
            // Вікно — УВЕСЬ коментар над оголошенням, а не три рядки.
            //
            // Перша версія дивилась на ±3 рядки й була зелена за побудовою:
            // виправдання пишуть не поруч із числом, а в KDoc над ним, і той
            // KDoc буває на двадцять рядків. Тобто сторож проти відмовок сам
            // не бачив би відмовки — рівно та пастка, яку ми ловимо в чужому
            // коді весь час. Ідемо вгору, доки над нами коментар або порожньо.
            var from = at
            var seen = 0
            while (from > 0 && seen < 25) {
                val prev = lines[from - 1].trim()
                if (prev.isEmpty() || prev.startsWith("//") || prev.startsWith("*") ||
                    prev.startsWith("/*")
                ) {
                    from--; seen++
                } else {
                    break
                }
            }
            lines.subList(from, minOf(lines.size, at + 2)).forEach { line ->
                excuses.firstOrNull { line.contains(it, ignoreCase = true) }
                    ?.let { guilty += "${c.name}: «$it» біля стелі — ${line.trim()}" }
            }
        }
        assertEquals(
            "Біля стелі стоїть відмовка. «Тимчасово» тут не буває: або число обґрунтоване " +
                "назавжди, або його треба повернути назад у цьому ж коміті.",
            emptyList<String>(),
            guilty,
        )
    }

