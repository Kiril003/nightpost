    private fun repoRoot(): File {
        var dir: File? = File("").absoluteFile
        while (dir != null && !File(dir, "core-design").isDirectory) dir = dir.parentFile
        return dir ?: fail("корінь репозиторію з core-design/ не знайдено") as Nothing
    }

    /**
     * Чиста функція — саме тому її можна перевірити на завідомо поганому джерелі,
     * не чіпаючи справжніх сторожів. Повертає опис розходження або `null`.
     */
    private fun drift(c: Ceiling, source: String): String? {
        val match = Regex("""private val ${Regex.escape(c.name)}\s*=\s*(\d+)""").find(source)
            ?: return "${c.name}: не знайдено — змінну перейменували або прибрали"
        val actual = match.groupValues[1].toInt()
        if (actual == c.expected) return null
        val weakened = (actual > c.expected && c.weakensWhen == Direction.GROWS) ||
            (actual < c.expected && c.weakensWhen == Direction.FALLS)
        return "${c.name}: ${c.expected} → $actual — ${if (weakened) "ПОСЛАБЛЕНО" else "посилено"}"
    }

    @Test
    fun `жодна стеля не змінилась мовчки`() {
        val root = repoRoot()
        val drifted = ledger.mapNotNull { c ->
            val file = File(root, c.path)
            assertTrue(
                "сторожа ${c.path} більше немає — стеля не «змінилась», її прибрали разом із файлом",
                file.isFile,
            )
            drift(c, file.readText())?.let { "${file.name}: $it" }
        }
        assertEquals(
            "Стелю ратчета змінено. Це дозволено — але не мовчки: онови число в " +
                "RatchetCeilingLedgerTest разом зі стелею і скажи в повідомленні коміта, чому. " +
                "Послаблення без причини — це зняття сторожа, лише написане цифрою.",
            emptyList<String>(),
            drifted,
        )
    }

    /** ДОКАЗ ЧЕРВОНОГО: піднята стеля мусить бути спіймана й названа послабленням. */
    @Test
    fun `реєстр ловить підняту стелю`() {
        val c = ledger.first { it.name == "cyrillicUiCeiling" }
        val verdict = drift(c, "    private val cyrillicUiCeiling = ${c.expected + 1}")
        assertEquals("cyrillicUiCeiling: ${c.expected} → ${c.expected + 1} — ПОСЛАБЛЕНО", verdict)
    }

    /**
     * ДОКАЗ ЧЕРВОНОГО НА СПРАВЖНЬОМУ ФАЙЛІ.
     *
     * Тест вище доводить логіку на рядку, який написав я — а отже доводить лише
     * те, що мій регекс збігається з моїм же прикладом. Тут береться **справжнє
     * джерело сторожа**, число в ньому підміняється в памʼяті, і сторож мусить
     * упасти. Це закриває шов між «функція працює» і «вона працює проти того
     * формату, який справді лежить у дереві» — саме той шов, на якому сьогодні
     * двічі впіймали мене: перевірка збігалась із власним припущенням.
     */
    @Test
    fun `реєстр ловить підняту стелю у справжньому джерелі`() {
        val c = ledger.first { it.name == "rawRadiusCeiling" }
        val real = File(repoRoot(), c.path).readText()
        assertNull("контроль: неторкане джерело мусить бути чистим", drift(c, real))

        val mutated = real.replace(
            "private val ${c.name} = ${c.expected}",
            "private val ${c.name} = ${c.expected + 40}",
        )
        assertTrue("підміна не спрацювала — формат джерела інший, ніж очікує тест", mutated != real)
        assertEquals("rawRadiusCeiling: ${c.expected} → ${c.expected + 40} — ПОСЛАБЛЕНО", drift(c, mutated))
    }

