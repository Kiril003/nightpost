/**
 * Реєстр стель. Сторож над сторожами.
 *
 * **Навіщо.** Наші ратчети тримають борг числом: «сирих кеглів не більше 524»,
 * «кириличних літералів не більше 1746». Таке число послаблюється **правкою
 * одного символу**, і в дифі це виглядає як константа, а не як зняття
 * перевірки. Заслін проти знятих сторожів (`GuardRemovalFirewallTest`) цього не
 * бачить і не може: рядок `private val ceiling = 524` не схожий на перевірку —
 * він схожий на число. Це його сліпа пляма, названа в його ж KDoc.
 *
 * За добу 30.08 дім тричі змінив поведінку разом із видаленням тесту, що її
 * стеріг. Стеля — четвертий спосіб втратити вартового, дешевший за три
 * попередні, бо не лишає по собі навіть порожнього рядка.
 *
 * **Що робить.** Тримає очікуване значення кожної стелі поруч із напрямком, у
 * якому вона слабшає. Будь-яка зміна числа валить цей тест, і полагодити його
 * можна лише правкою ЦЬОГО файла — тобто зміна стелі стає окремим рядком у
 * дифі, який рецензент побачить.
 *
 * **Це не заборона.** Стеля мусить падати — у цьому весь сенс ратчета. Тест
 * вимагає лише, щоб рух стелі був СКАЗАНИЙ вголос.
 *
 * **Чому тут є тести на власний червоний.** Ворота, які ніколи не бачили
 * червоного, — не ворота. `реєстр ловить підняту стелю` і `реєстр ловить
 * перейменовану змінну` згодовують сторожеві завідомо погане джерело і
 * вимагають, щоб він упав. Без них зелений прогін нічого не доводить: він так
 * само зелений, коли регекс не збігається ні з чим.
 *
 * **Сліпі плями, названі чесно:**
 *  - стереже рівно ті стелі, що перелічені тут; новий ратчет деінде лишається
 *    невидимим, доки хтось не допише його в реєстр;
 *  - себе не стереже — його теж можна відредагувати одним рухом;
 *  - не знає, ЧОМУ число змінилось: обґрунтування лишається на людині.
 */
