package local.phantom.companion.core.sensor.nav

/**
 * Свідчення СИРИХ супутникових вимірювань — єдине, чого фізичний шлюз не бачить.
 *
 * [SpoofGate] судить готовий `Location`: він ловить телепорт, нефізичну швидкість
 * і суперечність барометру. Але акуратна підміна не порушує жодного з цих правил —
 * вона видає послідовність цілком правдоподібних точок. Брехню там ще видно на
 * рівень нижче: у C/N0, у зсуві годинника приймача, у розбіжності фази й доплера.
 * Це рахує `:core-gnss`; сюди воно приходить уже як бали.
 *
 * Тип свій, а не `GnssIntegrity`: `:core-sensor` не залежить від `:core-gnss`, і
 * не має — переклад робить хост, який бачить обидва модулі.
 *
 * @param dopplerPhaseRmsM розбіжність фази й доплера, RMS у метрах. Для чесного
 *   сигналу — сантиметри; генератор, який не тримає когерентну фазу, дає метри.
 * @param note найсильніша причина українською — те, що показують оператору
 */
data class SkyIntegrity(
    val jammingScore: Double = 0.0,
    val spoofingScore: Double = 0.0,
    val usableSats: Int = 0,
    val dopplerPhaseRmsM: Double = 0.0,
    val note: String? = null,
)
