package local.phantom.companion.core.sensor.nav

/**
 * Зміщення пішохода від останньої довіреної точки — вихід числення кроків
 * (`:core-indoor`, `PedestrianContinuity`).
 *
 * Саме ЗМІЩЕННЯ, а не координата: привʼязку тримає той, хто її здобув, тобто
 * двигун. Знімок із «позицією» неминуче показав би вигадану позицію тоді, коли
 * привʼязки немає.
 *
 * @param accuracyM чесна 1σ від привʼязки, включно зі «сліпими» кроками
 * @param informative зміщення більше за власну похибку; хибне значення означає
 *   «людина, можливо, і не рухалась» — таке не має рухати мітку
 */
data class PedestrianDisplacement(
    val eastM: Double,
    val northM: Double,
    val accuracyM: Double,
    val informative: Boolean,
    val atMs: Long,
)

/**
 * Мить, у яку числення кроків треба привʼязати до світу.
 *
 * Публікується лише на ДОВІРЕНОМУ розвʼязку. Це не косметика: привʼязка до вже
 * підміненої координати пережила б саму атаку й тягнулась би далі як «власне
 * числення пристрою». Курс і швидкість ідуть разом, бо неузгодженість
 * «пристрій ↔ тіло» спостережувана рівно поки супутник ще живий і людина вже йде.
 */
data class PedestrianAnchor(
    val accuracyM: Double,
    val bearingDeg: Float?,
    val speedMps: Float?,
    val atMs: Long,
)
