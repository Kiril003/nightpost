package local.phantom.companion.core.sensor.nav

/**
 * НАСКІЛЬКИ СИЛЬНО маршрут ухиляється від небезпечної землі — один тумблер
 * на весь застосунок.
 *
 * Дві динамічні поправки вже їздять на [RoadGraph.routeTraced] через
 * `extraCostFactor` і вже працюють: [GnssIntegrityMap.costFactorAt] (тінь
 * глушилки, вивчена з власних фіксів) і [CoverGrid.costFactorAt] (відкрита
 * земля проти стіни). Досі обидві вмикалися РІВНО в одному місці —
 * `SpatialRoutingService.routeTo`, тобто лише коли людина тікає в укриття.
 * Звичайна поїздка «проведи мене туди» їх не бачила взагалі.
 *
 * Сила поправки — це не інженерне питання, а польове, і ВЛАСНИК ЙОГО ЩЕ НЕ
 * ВИРІШУВАВ. Тому число не вигадане: [AVOIDANT] — це рівно ті множники, на
 * яких уже їздить евакуація ([LocalRouter.DEFAULT_AVOIDANCE] і 0,7), бо
 * робоча відома основа краща за здогад. Коли власник скаже своє слово, зміна
 * думки коштує ОДИН рядок тут, а не розслідування по трьох викликах.
 *
 * Обидва множники ТІЛЬКИ КЕРМУЮТЬ і ніколи не забороняють: найгірше, що може
 * статися з повністю глухою клітиною, — вона коштує (1 + [jammingAvoidance])×
 * своєї довжини. Маршруту «немає» через них не буває, і жодна зі звітних
 * величин (довжина, час, `meanRisk`) не переписується — вони лишаються
 * справжніми числами ОБРАНОГО шляху.
 */
enum class RouteCaution(
    /**
     * Множник тіні глушилки: повністю глуха клітина коштує
     * (1 + це)× довжини. Див. [GnssIntegrityMap.costFactorAt].
     */
    val jammingAvoidance: Double,
    /**
     * Множник відкритої землі: клітина без жодної стіни поруч коштує
     * (1 + це)× довжини. Див. [CoverGrid.costFactorAt].
     */
    val coverAvoidance: Double,
) {
    /** Найкоротший шлях і нічого більше — поведінка, яку головний маршрут мав досі. */
    OFF(0.0, 0.0),

    /**
     * Половина від [AVOIDANT], і саме тому половина: поштовх, який виграє
     * лише там, де обʼїзд і так короткий. Тут немає власного заміру — це
     * свідомо похідне число, щоб два рівні не розповзалися нарізно.
     */
    CAUTIOUS(AVOIDANT_JAMMING / 2.0, AVOIDANT_COVER / 2.0),

    /**
     * Рівень евакуації. 1,2 — «глуха клітина коштує ~2,2× своєї довжини:
     * вартий справжнього обʼїзду, але не такий, щоб роутер намотав кілометр
     * заради одного поганого кварталу» ([LocalRouter.DEFAULT_AVOIDANCE]).
     * 0,7 — «відкрита земля коштує ~1,7×: стіни виграють справжні обʼїзди,
     * а не марафони».
     */
    AVOIDANT(AVOIDANT_JAMMING, AVOIDANT_COVER),
    ;

    companion object {
        /**
         * ЗАГЛУШКА, ЩО ЧЕКАЄ НА ВЛАСНИКА. Скільки оператор готовий проїхати
         * зайвого, щоб не вʼїхати в тінь глушилки чи на відкрите поле, —
         * питання поля, не коду. До його відповіді головний маршрут їде на
         * тому самому рівні, що й евакуація: якщо це число правильне для
         * дороги в укриття під обстрілом, воно тим більше не зашкодить
         * звичайній поїздці, а різнобій між двома шляхами був би гіршим за
         * будь-яке з двох чисел.
         */
        val EVERYDAY = AVOIDANT

        /** Те, на чому евакуація їздить із самого початку. Не змінювати нарізно з [EVERYDAY]. */
        val EVACUATION = AVOIDANT
    }
}

/**
 * Ці двоє лежать поза переліком навмисно: аргументи конструктора enum-константи
 * не бачать її ж companion, а [CAUTIOUS] мусить бути похідним від [AVOIDANT],
 * а не другим незалежним числом.
 */
private const val AVOIDANT_JAMMING = LocalRouter.DEFAULT_AVOIDANCE
private const val AVOIDANT_COVER = 0.7
