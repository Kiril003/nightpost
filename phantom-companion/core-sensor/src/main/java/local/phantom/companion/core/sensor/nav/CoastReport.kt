package local.phantom.companion.core.sensor.nav

/**
 * Що сказав лічильник шляху на цьому такті — і чому саме це окремий тип.
 *
 * У потоці не може бути голої порожнечі там, де шов працює: `null` невідрізненний
 * від «лічильника взагалі немає», а це те саме мовчання, яке в цьому дереві
 * коштувало найдорожче (див. [GraphCoasting] і його межі). Тому:
 *
 *  - [Ran] — лічильник відповів; усередині його власний вирок, зокрема чесне
 *    «не знаю» ([GraphCoasting.Coast.Lost]) з причиною з його словника;
 *  - [Refused] — до лічильника навіть не дійшло, і причина ШВА (немає фікса,
 *    немає графа поруч, шов розсинхронізувався, шов упав) названа словом;
 *  - `null` у потоці означає РІВНО ОДНЕ: постачальника графа не задано, тобто
 *    шва не існує. Інших значень у порожнечі немає.
 */
sealed interface CoastReport {

    /** Лічильник відпрацював такт і має що сказати. */
    data class Ran(val coast: GraphCoasting.Coast) : CoastReport

    /**
     * Такт до лічильника не дійшов. [reason] — словник ШВА, а не
     * [GraphCoasting.Reason]: змішувати їх означало б приписати лічильникові
     * відмову, якої він не виносив.
     */
    data class Refused(val reason: String) : CoastReport
}
