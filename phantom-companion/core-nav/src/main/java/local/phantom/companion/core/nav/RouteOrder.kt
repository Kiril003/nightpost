package local.phantom.companion.core.nav

import local.phantom.companion.core.net.map.RouteVariant

/**
 * Хто рахує маршрут першим — і чому це не дрібниця.
 *
 * Донедавна порядок був такий: `osrm.routeDetailed(...) ?: offlineMeshRoute(...)`.
 * Тобто КОЖЕН маршрут і КОЖНА перебудова спершу йшли в мережу — до чужого
 * демо-сервера — і чекали до 12 секунд таймауту, тоді як на пристрої лежав
 * готовий граф доріг, здатний відповісти за мілісекунди. Водій, що зійшов з
 * маршруту, стояв без перебудови не тому, що рушія немає, а тому, що рушій
 * стояв другим у черзі.
 *
 * Тут порядок зворотний і названий уголос: **граф на пристрої — перший**.
 * Мережа лишається, але вмикається лише там, де свій граф чесно каже «не
 * знаю»: коридор поза кешованою мережею, надто велика відстань, порожній граф.
 *
 * Функція навмисно чиста і живе окремо від контейнера: інакше наступний
 * рефакторинг тихо поверне мережу вперед, і ми дізнаємось про це від власника
 * через місяць. [RouteOrderTest] червоніє саме на такий переворот.
 */
suspend fun routeGraphFirst(
    /** Граф на пристрої. null — коридор не покритий; це не помилка, це «не знаю». */
    onDevice: suspend () -> List<RouteVariant>?,
    /** Мережа. Її черга настає ЛИШЕ після відмови графа. */
    network: suspend () -> List<RouteVariant>?,
): List<RouteVariant>? = onDevice()?.takeIf { it.isNotEmpty() } ?: network()
