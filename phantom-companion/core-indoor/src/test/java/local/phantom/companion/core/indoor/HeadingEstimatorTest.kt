package local.phantom.companion.core.indoor

import local.phantom.companion.core.indoor.pdr.HeadingEstimator
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import kotlin.math.PI

/**
 * Тести оцінки курсу: гіроскоп плюс магнітометр із падінням довіри там, де
 * магнітометру вірити не можна.
 *
 * Найважливіше — детектор магнітної аномалії. У метро поле спотворене всім
 * одразу: армована обробка тунелю, рейки, контактна мережа з сотнями ампер,
 * тяговий двигун ескалатора, сам вагон. Модуль поля стрибає з ~50 мкТл до 90 і
 * назад за секунди. Курс за таким магнітометром не «трохи неточний», а
 * повернутий на десятки градусів у випадковий бік — і саме він створює той
 * системний дрейф, який потім доводиться виправляти суміщенням цілої кривої.
 * Тому різка зміна МОДУЛЯ поля мусить миттєво обнуляти довіру.
 */
class HeadingEstimatorTest {

    /** Спокійне, чесне земне поле під Києвом ~50 мкТл. */
    private val earthUt = 50.0

    private fun wrap(r: Double): Double {
        val tau = 2.0 * PI
        return ((r % tau) + tau) % tau
    }

    // ————————————————————————————————————————————————————————————————
    // Гіроскоп: інтеграція та дрейф
    // ————————————————————————————————————————————————————————————————

    @Test
    fun `гіроскоп інтегрує поворот із правильним знаком`() {
        // Додатна кутова швидкість навколо вертикалі — поворот проти
        // годинникової, тобто ЗМЕНШЕННЯ азимута. Крутимо 0.1 рад/с рівно 5 с:
        // курс має впасти на 0.5 рад (з обгортанням у [0, 2π)).
        val est = HeadingEstimator()
        est.seedHeading(0.0, 0.1)
        val omega = 0.1
        // Годинник свідомо стартує не з 0: у коді lastGyroMs==0 — це сентінел
        // «не ініціалізовано», тож elapsedRealtime у реальності теж ніколи не 0.
        var t = 1000L
        est.onGyro(t, omega) // перший семпл лише ставить годинник
        repeat(50) { est.onGyro((t + 100).also { t += 100 }, omega) } // 50×100 мс = 5 с
        assertEquals(
            "курс після 5 с при 0.1 рад/с має бути −0.5 рад",
            wrap(-0.5), est.headingRad, 1e-6,
        )
    }

    @Test
    fun `невизначеність курсу росте з ЧАСОМ, а не з відстанню`() {
        // На відміну від похибки PDR (росте з кроками), дрейф гіроскопа — це
        // властивість самого сенсора: дисперсія росте лінійно з часом навіть коли
        // людина стоїть. Звіряємо з точною моделлю σ² = σ₀² + q·t.
        val est = HeadingEstimator()
        val sigma0 = 0.1
        est.seedHeading(0.0, sigma0)
        var t = 1000L // не з 0: див. коментар про сентінел lastGyroMs
        est.onGyro(t, 0.0)
        repeat(100) { est.onGyro((t + 100).also { t += 100 }, 0.0) } // 10 с спокою
        val tSec = 10.0
        // GYRO_RANDOM_WALK_VAR_PER_S у коді private, тож дублюємо (0.02 рад/с)²
        // = 4e-4 навмисно: якщо код змінить сталу, цей тест впаде й нагадає.
        val gyroWalkVarPerS = 4.0e-4
        val expected = kotlin.math.sqrt(sigma0 * sigma0 + gyroWalkVarPerS * tSec)
        assertEquals(
            "невизначеність курсу має рости з часом за моделлю випадкового блукання",
            expected, est.uncertaintyRad, 1e-6,
        )
    }

    @Test
    fun `розрив потоку гіроскопа не інтегрується`() {
        // Додаток згорнули на 10 с. Інтегрувати кутову швидкість крізь розрив
        // не можна — курс стрибнув би на десятки градусів на порожньому місці.
        val est = HeadingEstimator()
        est.seedHeading(1.0, 0.1)
        est.onGyro(0L, 0.5)
        val before = est.headingRad
        est.onGyro(10_000L, 0.5) // dt=10 с > MAX_GYRO_GAP_S
        assertEquals("курс не має інтегруватись крізь розрив потоку", before, est.headingRad, 1e-12)
    }

    // ————————————————————————————————————————————————————————————————
    // Комплементарне зведення з магнітометром
    // ————————————————————————————————————————————————————————————————

    @Test
    fun `у чистому полі курс підтягується до магнітного`() {
        // Гіроскоп стартував із хибним курсом 1.0 рад, магнітометр стабільно
        // показує 0.0 при спокійному полі. Комплементарний фільтр має повільно
        // звести курс до магнітного, щойно довіра наросте.
        val est = HeadingEstimator()
        est.seedHeading(1.0, 0.5)
        var t = 0L
        // 20 с стабільного поля при 20 Гц: перші 2 с — карантин відновлення,
        // далі довіра росте й курс сходить до 0.
        repeat(400) {
            t += 50
            est.onMagnetic(t, headingRad = 0.0, fieldMagnitudeUt = earthUt)
        }
        assertTrue("довіра до магнітометра мала наростити", est.magTrust > 0.5)
        assertTrue(
            "курс мав підтягнутись від 1.0 до ~0 магнітного, а лишився ${est.headingRad}",
            est.headingRad < 0.35,
        )
        assertFalse("у спокійному полі аномалії бути не повинно", est.anomaly)
    }

    // ————————————————————————————————————————————————————————————————
    // Детектор магнітної аномалії — серце модуля
    // ————————————————————————————————————————————————————————————————

    @Test
    fun `різкий стрибок модуля поля миттєво обнуляє довіру`() {
        // Людина проходить повз тяговий двигун ескалатора: поле стрибає 50→88
        // мкТл за один семпл. Це відмова довіри — magTrust має впасти до нуля
        // МИТТЄВО, а прапор аномалії піднятись.
        val est = HeadingEstimator()
        est.seedHeading(0.5, 0.3)
        var t = 0L
        repeat(400) { // напрацьовуємо довіру на спокійному полі
            t += 50
            est.onMagnetic(t, headingRad = 0.5, fieldMagnitudeUt = earthUt)
        }
        assertTrue("перед аномалією довіра мала існувати", est.magTrust > 0.4)

        t += 50
        est.onMagnetic(t, headingRad = 2.0, fieldMagnitudeUt = 88.0) // залізо поруч
        assertTrue("різкий стрибок поля — це аномалія", est.anomaly)
        assertEquals("довіра до магнітометра має впасти миттєво до нуля", 0.0, est.magTrust, 1e-12)
    }

    @Test
    fun `під час аномалії брехливий магнітний курс не тягне оцінку`() {
        // Найнебезпечніший сценарій: біля вагона магнітометр упевнено показує
        // курс, повернутий на 90°. Якщо піддатись — уся крива поїде. Курс має
        // лишитись тим, що дав гіроскоп/seed, а не аномальний магнітний.
        //
        // Опорне поле спершу встановлюється чистим (детектор аномалії працює за
        // ВІДХИЛЕННЯМ від опори, тож перший семпл сам стати аномалією не може —
        // це і є правильна фізика: одну точку ні з чим порівняти).
        val est = HeadingEstimator()
        est.seedHeading(0.5, 0.3)
        var t = 0L
        repeat(100) { // ~5 с чистого поля 50 мкТл, курс узгоджений із seed
            t += 50
            est.onMagnetic(t, headingRad = 0.5, fieldMagnitudeUt = earthUt)
        }
        val headingBefore = est.headingRad
        // Тепер залізо: поле 95 мкТл і брехливий курс 2.0 рад.
        t += 50
        est.onMagnetic(t, headingRad = 2.0, fieldMagnitudeUt = 95.0)
        assertTrue("стрибок 50→95 мкТл — аномалія", est.anomaly)
        assertEquals(
            "курс не має піддатись аномальному магнітометру",
            headingBefore, est.headingRad, 1e-9,
        )
    }

    @Test
    fun `поле поза земним діапазоном — теж аномалія`() {
        // Магніт чохла впритул до сенсора або несправність дають 200 мкТл. Це
        // вже не вимір поля Землі — довіри нуль.
        val est = HeadingEstimator()
        est.seedHeading(0.0, 0.3)
        est.onMagnetic(1000L, headingRad = 1.0, fieldMagnitudeUt = 200.0)
        assertTrue("поле 200 мкТл не є земним — аномалія", est.anomaly)
        assertEquals(0.0, est.magTrust, 1e-12)
    }

    @Test
    fun `довіра відновлюється повільно після того, як поле заспокоїлось`() {
        // Несиметрія за задумом: довіра падає миттєво, а повертається лише після
        // карантину спокою. Проходимо аномалію, потім тримаємо чисте поле —
        // довіра має ПОЧАТИ рости, але не стрибнути назад одразу.
        val est = HeadingEstimator()
        est.seedHeading(0.0, 0.3)
        est.onMagnetic(1000L, headingRad = 0.0, fieldMagnitudeUt = earthUt)
        est.onMagnetic(1100L, headingRad = 0.0, fieldMagnitudeUt = 90.0) // аномалія
        assertEquals(0.0, est.magTrust, 1e-12)

        var t = 1100L
        // Одразу після заспокоєння, ще в межах карантину, довіри нема.
        est.onMagnetic(t + 500, 0.0, earthUt)
        assertEquals("у карантині довіра ще нульова", 0.0, est.magTrust, 1e-12)

        // Тримаємо спокій довго — довіра має наростити.
        t += 500
        repeat(300) {
            t += 50
            est.onMagnetic(t, 0.0, earthUt)
        }
        assertTrue("після карантину й тривалого спокою довіра має відновитись", est.magTrust > 0.3)
    }

    @Test
    fun `застарілий магнітометр обнуляє довіру навіть без нових вимірів`() {
        // Потік магнітометра урвався (аномалія триває або сенсор замовк). Довіра
        // не має застрягти на старому рівні — черговий семпл гіроскопа має її
        // згасити, коли з останнього магвиміру минуло понад поріг застарілості.
        val est = HeadingEstimator()
        est.seedHeading(0.0, 0.3)
        var t = 0L
        repeat(400) {
            t += 50
            est.onMagnetic(t, 0.0, earthUt)
        }
        assertTrue("довіра мала існувати", est.magTrust > 0.3)
        // Гіроскоп цокає далі без жодного магвиміру. Згасання довіри вшите в
        // хід гіроскопа, тож потрібні послідовні семпли (не один стрибок крізь
        // розрив), поки з останнього магвиміру не мине поріг застарілості.
        val lastMag = t
        est.onGyro(t + 100, 0.0) // ініціалізує годинник гіроскопа
        t += 100
        while (t - lastMag <= 3_500L) {
            t += 100
            est.onGyro(t, 0.0)
        }
        assertEquals("застарілий магнітометр має обнулити довіру", 0.0, est.magTrust, 1e-12)
    }

    // ————————————————————————————————————————————————————————————————
    // Сміття
    // ————————————————————————————————————————————————————————————————

    @Test
    fun `NaN на вході ігнорується, а не отруює курс`() {
        val est = HeadingEstimator()
        est.seedHeading(0.7, 0.2)
        est.onGyro(0L, 0.1)
        est.onGyro(100L, Double.NaN)
        est.onMagnetic(200L, Double.NaN, earthUt)
        est.onMagnetic(300L, 0.0, Double.NaN)
        assertTrue("курс має лишитись скінченним попри NaN на вході", est.headingRad.isFinite())
    }
}
