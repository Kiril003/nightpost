package local.phantom.companion.core.ai.context

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * «Не знаю, де ти» мусить нести ПРИЧИНУ, бо причини дві й ліки різні.
 *
 * `[LOCATION:unknown]` стояв за двома протилежними станами: **дозволу немає**
 * і **дозвіл є, фіксу ще нема**. Для моделі це один рядок, отже для людини —
 * одна відповідь на два різні світи. Перший лікується двома дотиками в
 * налаштуваннях; другий — підійти до вікна. Сказати «не знаю» на обидва
 * означає не допомогти в жодному.
 *
 * Знання при цьому **існувало** — його викидали за крок до моделі:
 * `AppContainer.lastKnownByProvider` ловить `SecurityException` у `null` під
 * `@Suppress("MissingPermission")`, тож до форматера доїжджає порожнеча без
 * причини. Глушник заразом робить це місце невидимим для лінта назавжди.
 *
 * Це мʼякший родич `nav.status`, де жорсткий `threats_count = 0` був
 * невідрізнимий від «ніхто не дивився». Там **невідомість вдягала одяг
 * виміру**; тут вона чесна щодо значення й **губить причину**. Спільне одне:
 * стан, який щось знає про світ, зводиться до стану, який не знає нічого.
 *
 * ── ЦЕЙ ТЕСТ НЕ ЧЕРВОНІЄ НА СТАРОМУ КОДІ, І Я КАЖУ ЦЕ ПРЯМО ──
 * Спершу я написав тут, що він падає на `assertNotEquals`. Це неправда:
 * на старому `format(fix, address)` параметра `permitted` не існує, тож він
 * **не зібрався б**, а тест, що не збирається, нічого не доводить — він лише
 * виглядає червоним. Дім уже двічі за добу ловив саме цю підміну, і я мало
 * не лишив третю, у власному коментарі.
 *
 * Отже чесно: **це сторож нового контракту, а не доказ старого дефекту.**
 * Дефект доведено ЧИТАННЯМ, і воно однозначне — у старому тілі стояв рівно
 * один рядок `if (fix == null) return "[LOCATION:unknown]"`, тобто обидві
 * причини поверталися тим самим рядком за побудовою, без жодної гілки, де
 * вони могли б розійтися. Тут нема чого відтворювати прогоном: у коді не
 * існувало місця, здатного їх розрізнити.
 * Сусідній [LocationContextProviderTest] і далі закріплює `[LOCATION:unknown]`
 * для випадку «дозвіл є, фікса нема» — і мусить лишатись зеленим.
 *
 * ── ЧОГО ЦЕЙ ТЕСТ НЕ БАЧИТЬ ──
 *  • Він не перевіряє, що хтось справді питає дозвіл. Форматер чесний рівно
 *    настільки, наскільки чесний той, хто передає йому `permitted`;
 *    незапитаний дозвіл виглядатиме як наявний.
 *  • Він не знає, чи модель СКАЖЕ причину людині — ми лише перестаємо її
 *    ховати.
 *  • Він нічого не каже про решту 29 `@Suppress` у дереві: глушник над
 *    правилом робить місце невидимим, і Android Lint, на відміну від ESLint,
 *    **не має правила про мертві глушники** — тобто цей борг не просто не
 *    виміряний, а й невимірний наявним інструментом.
 */
class LocationPermissionCauseTest {

    @Test
    fun `a denied permission does not look like a missing fix`() {
        val denied = LocationContextFormatter.format(fix = null, permitted = false)
        val noFix = LocationContextFormatter.format(fix = null, permitted = true)

        assertNotEquals(
            "«дозволу немає» і «фіксу немає» дають однаковий рядок — модель не може " +
                "назвати людині причину, хоч причина була відома на крок раніше",
            denied,
            noFix,
        )
        assertEquals("[LOCATION:unknown]", noFix)
        assertTrue(
            "відмова мусить називати себе словом, зрозумілим моделі. Було: $denied",
            denied.contains("дозвол"),
        )
    }

    /**
     * Друга половина контракту: причина не має права заступати дані. Якщо
     * дозвіл є і фікс є — заголовок мусить лишитись байт-у-байт тим самим,
     * інакше я поламав би кожен існуючий тест на закріплення промпту заради
     * випадку, що трапляється рідше.
     */
    @Test
    fun `a granted permission changes nothing about a real fix`() {
        val fix = LocationFix(50.4501, 30.5234)

        assertEquals(
            "наявний дозвіл не сміє міняти вигляд справжнього фікса",
            LocationContextFormatter.format(fix),
            LocationContextFormatter.format(fix, permitted = true),
        )
    }

    /**
     * І межа, яку легко переступити з добрих намірів: коли дозволу немає,
     * координат бути не може — але якщо вони якимось шляхом усе ж прийшли
     * (кеш, попередній запуск), причина мусить перемогти. Показати координати
     * поруч зі «немає дозволу» означало б суперечити самому собі в одному рядку.
     */
    @Test
    fun `denial wins over a stale fix rather than contradicting it`() {
        val out = LocationContextFormatter.format(
            fix = LocationFix(50.4501, 30.5234),
            permitted = false,
        )
        assertTrue(
            "рядок не може одночасно казати «дозволу немає» і показувати координати. Було: $out",
            !out.contains("50.4501"),
        )
    }
}
