#!/usr/bin/env bash
# Внести дорожній пакет у телефон власника — і довести, що він подіяв.
#
# Ручний імпорт НЕ перевіряє версію пакета (importFromPath дивиться лише на
# таблицю `ways` і колонку `tags`), тож цей шлях працює вже сьогодні: ані
# стеля `SUPPORTED_FORMAT_MAX` на ПК, ані ендпоїнт road-packs тут ні до чого.
#
#   scripts/install-road-pack.sh [шлях-до-пакета]
#
# Скрипт САМ нічого не імпортує: внесення йде через системний провідник
# файлів (SAF), а його не автоматизувати з adb. Скрипт кладе файл на телефон,
# каже точні дотики й після цього забирає докази.
set -uo pipefail

PACK="${1:-/home/kyrylo/phantom_ai/road-mesh-bake/phantom_road_mesh.kyiv-v2.db}"
ADB="${ADB:-adb}"
DEST_DIR=/sdcard/Download
DEST="$DEST_DIR/$(basename "$PACK")"

if [ ! -f "$PACK" ]; then
    echo "немає пакета: $PACK" >&2
    exit 1
fi

echo "== пакет =="
ls -lh "$PACK" | awk '{print "  розмір:", $5}'
echo "  версія схеми: $(sqlite3 "$PACK" 'PRAGMA user_version' 2>/dev/null || echo '?')"
echo "  доріг: $(sqlite3 "$PACK" 'SELECT COUNT(DISTINCT id) FROM ways' 2>/dev/null || echo '?')"
echo "  sha256: $(sha256sum "$PACK" | cut -c1-16)…"

# Вибір апарата, а не «перший-ліпший». На цій машині поруч із телефоном
# майже завжди крутиться емулятор іншого фронту, і `adb get-state` тоді
# падає з «more than one device» — тобто скрипт казав «телефона немає»,
# маючи телефон під носом. Гірше було б протилежне: мовчки покласти
# 48 МБ в емулятор і доповісти про успіх.
SERIAL="${SERIAL:-}"
if [ -z "$SERIAL" ]; then
    mapfile -t REAL < <("$ADB" devices | awk '$2=="device" && $1 !~ /^emulator-/ {print $1}')
    if [ "${#REAL[@]}" -eq 0 ]; then
        echo >&2
        echo "справжнього телефона на кабелі немає — далі не йду." >&2
        "$ADB" devices | sed 's/^/  /' >&2
        exit 2
    fi
    if [ "${#REAL[@]}" -gt 1 ]; then
        echo "апаратів кілька — назви котрий: SERIAL=<серійник> $0" >&2
        printf '  %s\n' "${REAL[@]}" >&2
        exit 2
    fi
    SERIAL="${REAL[0]}"
fi
echo
echo "апарат: $SERIAL"
ADB="$ADB -s $SERIAL"

echo
echo "== кладу на телефон =="
$ADB push "$PACK" "$DEST" || exit 1

cat <<'STEPS'

== далі руками, на телефоні (три дотики) ==
  1. Налаштування → Діагностика → «Точність»
  2. «Внести файл пакета вручну»
  3. у провіднику: Downloads → phantom_road_mesh.kyiv-v2.db

ЩО МАЄ ЗʼЯВИТИСЬ ПІД РИСКОЮ «внесено доріг»:
  ✅ «З тегами доріг: прокладання по класу дороги, час у дорозі — з дозволеної
     швидкості на знаку, де OSM її має.»  — сірим. Пакет прийнято.
  ❌ Червоним «Пакет спечено старим рецептом…» — значить поклали не той файл.

ПЕРЕЗАПУСК НЕ ПОТРІБЕН: масовий імпорт тепер будить лічильник мережі, і кеш
коридорів перебудується на першому ж запиті. (До 30.08 не будив — саме тому
цей рядок тут і стоїть.)

== чим доводимо, що подіяло ==
  1. Прокласти В ЗАСТОСУНКУ той самий маршрут, що й до внесення.
  2. Подивитись на час прибуття: ДО нього не було взагалі (основа ASSUMED,
     ми свідомо не малюємо годинника над вгадкою), ПІСЛЯ — має зʼявитись.
  3. Забрати скриню і прочитати рядок `route`:  scripts/pull-blackbox.sh
     Основа мусить бути CLASS або POSTED. Якщо лишилась ASSUMED — пакет не
     доїхав до маршрутизатора, хай би що казав екран імпорту.
STEPS
