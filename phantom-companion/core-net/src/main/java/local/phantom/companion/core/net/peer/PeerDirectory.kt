package local.phantom.companion.core.net.peer

import java.security.MessageDigest
import java.util.Base64
import local.phantom.companion.core.net.crypto.Ed25519
import local.phantom.companion.core.net.crypto.bytesToHex

/**
 * Як знайти людину за іменем, не збудувавши каталогу.
 *
 * Питання власника було двома реченнями: «як людей шукати?» і «список всіх
 * користувачів?? щоб мошеники по всім працювали??». Обидва мають одну
 * відповідь, і вона в формі протоколу, а не в правилах доступу: сервер знає
 * лише SHA-256 імені, і питати його можна ЛИШЕ повним іменем, яке тобі вже
 * назвали. Переліку немає не тому, що ручку сховали, а тому, що з хешів її
 * не скласти: список імен, який можна віддати, тут просто не існує.
 *
 * Це речення стало правдою лише з v2, і варто знати, чому воно нею не було.
 * До v2 хешем ішов ПОШУК, а публікація везла `handle` відкритим текстом, бо
 * підписане речення накривало саме імʼя — тобто сервер бачив кожне
 * опубліковане імʼя в мить публікації й міг скласти рівно той перелік. Тепер
 * підпис накриває ХЕШ ([publishPayload], [withdrawPayload]), у тілі запиту
 * їде `handle_hash`, і імʼя не покидає апарата взагалі — ні при пошуку, ні
 * при публікації, ні при відклику. Ціна названа й не схована: перебір по
 * словнику лишається можливим (хеш короткого слова дешевий), і форму імені
 * (5-32 з a-z0-9_) тепер тримає ТІЛЬКИ телефон — сервер із 64 hex її не
 * бачить.
 *
 * Друга половина тієї самої обіцянки — у конверті. Хеш прибрав імʼя з ЗАПИТУ,
 * але в самому запрошенні PH2 лишалось показне імʼя пристрою («Марта»,
 * «Ноутбук»), тож база все одно складалася в перелік людських імен із
 * ключами. Імені для пошуку там не було, звʼязок «слово, яке продиктували ↔
 * ключ» із неї не виводився — і все ж «жодного імені» було неправдою. Власник
 * вирішив: переліку не має бути ніякого. Тому [addressless] зрізає й `name`, і
 * в конверті довідника не лишається жодного людського рядка — лише відбиток
 * ключа й самі ключі.
 *
 * Ціна названа й видна на склі: знайдений через довідник показується коротким
 * ідентифікатором із тегом «не звірено», доки імʼя не прийде від самої людини
 * або зі звіреного запрошення. Порожнім рядком він не показується ніде.
 *
 * Публікація добровільна й підписана. Запис у довіднику — це запрошення PH2,
 * підписане тим самим Ed25519 ключем, що всередині нього; сервер його
 * переписати не може, а якщо перепише — [verify] це побачить на телефоні.
 * Тому довіднику не треба вірити: він або віддає ключ, який людина підписала
 * сама, або не віддає нічого.
 *
 * І все ж це НЕ доведене джерело ключа: підпис доводить, що запис склав
 * власник ключа, а не що цей ключ належить тій людині, яку ти шукав. Хто
 * зайняв імʼя першим — той його і має. Тому контакт звідси приходить
 * незвіреним ([PeerIdentity.KeySource.REMOTE]), і звірка ключів лишається
 * тією самою церемонією, що й була.
 */
object PeerDirectory {

    /**
     * Під цим підписується публікація.
     *
     * `v2` — не косметика: у v1 підпис накривав ІМʼЯ, тож імʼя мусило приїхати
     * на сервер, щоб підпис було з чим звірити. Версія в рядку означає, що
     * підпис v1 не звіриться з реченням v2 і навпаки; двох чинних форм немає
     * ні тут, ні на сервері.
     */
    const val PUBLISH_PREFIX = "PH-DIR-v2"

    /** І окремо — зняття. Інакше підпис публікації знімав би імʼя. */
    const val WITHDRAW_PREFIX = "PH-DIR-del-v2"

    /** Довше сервер не тримає — тож телефон і не просить. */
    const val MAX_TTL_SECONDS = 30L * 24 * 60 * 60

    /**
     * Найкоротше імʼя, яке ще можна ОПУБЛІКУВАТИ.
     *
     * Вісім, а не пʼять, і це захід проти словника, а не проти людини. Адреса
     * запису — голий `sha256` імені (див. [handleHash]), тож дамп таблиці
     * перебирається офлайн: на одній 4090 усі пʼятизначні імена лягають за
     * 0,003 с, семизначні — за 4,3 с. Кожен доданий знак множить простір на 37;
     * 5 → 8 множить його на 50 653, і коштує це рівно одного речення на екрані.
     *
     * Це НЕ робить відбиток таємницею — словник із «людських» слів однаково
     * швидкий. Вартість перебору лікується розтягуванням (Argon2id, наступною
     * хвилею), а довжина лише прибирає найдешевший випадок. Обидва заходи
     * потрібні, і жоден не заступає другого.
     */
    const val MIN_PUBLISH_LENGTH = 8

    /**
     * Латиниця нижнього регістру, цифри й підкреслення, 5..32.
     *
     * Вужче за те, що людина набере: імʼя мусить пережити те, що його
     * ПРОДИКТУЮТЬ. Те саме слово кирилицею, з апострофом чи з великої літери —
     * це вже інший хеш і вже інша людина, а на слух усе це одне й те саме.
     *
     * Лишається від ПʼЯТИ навмисно: це форма, яку сервер ще може тримати —
     * записи, опубліковані старшими збірками. Шукати їх і знімати їх мусить
     * бути можна, інакше правило, введене СЬОГОДНІ, замикало б імʼя, видане
     * вчора, до кінця строку.
     */
    private val SHAPE = Regex("^[a-z0-9_]{5,32}$")

    /** Те саме, але з нижньою межею публікації. */
    private val PUBLISH_SHAPE = Regex("^[a-z0-9_]{$MIN_PUBLISH_LENGTH,32}$")

    /**
     * Імʼя в тій єдиній формі, яку знає сервер, або null — якщо це не імʼя.
     *
     * Питає про ІСНУЮЧИЙ запис: пошук, зняття, звірка. Тому терпить і коротке —
     * див. [SHAPE].
     */
    fun normalise(raw: String?): String? {
        val bare = raw?.trim()?.removePrefix("@")?.lowercase() ?: return null
        return bare.takeIf { SHAPE.matches(it) }
    }

    /**
     * Імʼя, яке можна завести ЗАРАЗ, або null.
     *
     * Окремо від [normalise] рівно тому, що правило нове: зняти чи знайти
     * старе коротке імʼя — можна завжди, завести нове коротке — вже ні.
     */
    fun normaliseForPublish(raw: String?): String? {
        val bare = raw?.trim()?.removePrefix("@")?.lowercase() ?: return null
        return bare.takeIf { PUBLISH_SHAPE.matches(it) }
    }

    fun isHandle(raw: String?): Boolean = normalise(raw) != null

    /** Те, що бачить сервер замість імені. Приймає імʼя в будь-якому регістрі. */
    fun handleHash(handle: String): String =
        bytesToHex(
            MessageDigest.getInstance("SHA-256")
                .digest(handle.lowercase().toByteArray(Charsets.UTF_8)),
        )

    /** Форма адреси: рівно те, що [handleHash] уміє видати. */
    private val ADDRESS = Regex("^[0-9a-f]{64}$")

    /**
     * Конверт для довідника: без адреси й БЕЗ ЖОДНОГО ЛЮДСЬКОГО РЯДКА.
     *
     * Зрізаються дві різні речі з двох різних причин. Адреса — бо вона
     * розповіла б серверові, у якій мережі стоїть телефон. Показне імʼя
     * (`name`) — бо доки воно їхало, сервер, який «не має списку людей», тримав
     * у базі перелік людських імен із ключами: імені ДЛЯ ПОШУКУ там не було,
     * але «жодного імені» було неправдою, і власник ухвалив, що переліку не
     * має бути ніякого.
     *
     * Лишається рівно машинне: відбиток ключа, два ключі, порожня адреса.
     * Знайдений через довідник показується як `@нік`, доки імʼя не прийде від самої людини; код ключа в рядок не йде ([rows] імʼя не підставляє).
     */
    fun addressless(invite: PeerInvite.Invite): PeerInvite.Invite =
        invite.copy(host = "", port = 0, name = "")

    /**
     * Речення, під яким стоїть підпис публікації. Бере ГОТОВУ адресу, а не
     * імʼя, і сама нічого не хешує — навмисно.
     *
     * Вада, через яку писалась v2, була саме в розбіжності: підписувалось одне
     * (імʼя), а в тілі запиту їхало те саме імʼя, і сервер бачив його. Тепер
     * викликач рахує [handleHash] ОДИН раз і кладе один і той самий рядок і в
     * тіло, і сюди — розійтись їм ніде. [require] тут не оборона від зловмисника,
     * а сторож проти власної помилки: імʼя, підсунуте замість адреси, дало б
     * цілком дійсний підпис під неправильним реченням, і побачити це можна було
     * б лише на живому сервері.
     */
    fun publishPayload(handleHash: String, invite: String, expSeconds: Long): ByteArray {
        require(ADDRESS.matches(handleHash)) { "адреса запису — це sha256 імені, 64 hex" }
        return "$PUBLISH_PREFIX|$handleHash|$invite|$expSeconds".toByteArray(Charsets.UTF_8)
    }

    fun withdrawPayload(handleHash: String, expSeconds: Long): ByteArray {
        require(ADDRESS.matches(handleHash)) { "адреса запису — це sha256 імені, 64 hex" }
        return "$WITHDRAW_PREFIX|$handleHash|$expSeconds".toByteArray(Charsets.UTF_8)
    }

    /** base64url без набивки — так, як цей підпис читає сервер. */
    fun sign(payload: ByteArray, privateKey: ByteArray): String =
        Base64.getUrlEncoder().withoutPadding().encodeToString(Ed25519.sign(privateKey, payload))

    /**
     * Те, що віддав сервер. [pubKey] сервер не повертає — поле лишається
     * порожнім і перевіряється лише тоді, коли викликач знає ключ наперед
     * (зняття свого імені, тест, майбутній формат відповіді).
     */
    data class Record(
        val handle: String,
        val invite: String,
        val sig: String,
        val expSeconds: Long,
        val pubKey: String = "",
    )

    /**
     * Кожна відмова має власне слово. «Нікого не знайшов» і «знайшов, але
     * запис підроблено» — це дві різні розмови з людиною, і зводити їх до
     * порожнього списку означало б сховати другу.
     */
    sealed interface Verdict {
        data class Trusted(val invite: PeerInvite.Invite) : Verdict

        /** Не імʼя: не та абетка, не та довжина. */
        data object BadHandle : Verdict

        /** Замість запрошення прийшло щось інше. */
        data object BadCode : Verdict

        /** Запис несе адресу — довідник її не тримає й не має права додати. */
        data object HasAddress : Verdict

        data object Expired : Verdict

        /** Ключ у запрошенні не той, під яким запис очікували. */
        data object WrongKey : Verdict

        /** Підпис не сходиться з ключем із самого запрошення. */
        data object BadSignature : Verdict
    }

    fun verify(record: Record, nowMs: Long): Verdict {
        val handle = normalise(record.handle) ?: return Verdict.BadHandle
        if (record.expSeconds <= 0L || record.expSeconds * 1_000L <= nowMs) return Verdict.Expired
        // Адреса в записі — не дрібниця й не сумісність: телефон, який її
        // послухається, першим же листом піде за нею, тобто дасть серверові
        // вибрати, куди. Порожня адреса означає «шукай сам» — маяком і сховком.
        //
        // Стеля тут [PeerInvite.MAX_CODE], а не [PeerInvite.ENVELOPE_MAX]: межу
        // 512 тримає сам сервер (`directory.py:86`), і звузити її ще й тут
        // означало б відмовити записам, які він уже роздає.
        val invite = when (
            val seen = PeerInvite.addressless(record.invite, maxChars = PeerInvite.MAX_CODE)
        ) {
            is PeerInvite.Addressless.Ok -> seen.invite
            PeerInvite.Addressless.HasAddress -> return Verdict.HasAddress
            else -> return Verdict.BadCode
        }
        val key = unB64(invite.pubKey) ?: return Verdict.BadSignature
        if (record.pubKey.isNotBlank()) {
            val declared = unB64(record.pubKey) ?: return Verdict.WrongKey
            if (!declared.contentEquals(key)) return Verdict.WrongKey
        }
        val sig = unB64(record.sig) ?: return Verdict.BadSignature
        // Адреса рахується ТУТ, зі знаного імені, а не береться з відповіді:
        // сервер її не повертає й не мусить — інакше він міг би підсунути
        // запис під іншим іменем, і підпис під ним би сходився.
        val payload = publishPayload(handleHash(handle), record.invite, record.expSeconds)
        if (!Ed25519.verify(key, payload, sig)) return Verdict.BadSignature
        return Verdict.Trusted(invite)
    }

    /** Один знайдений — або жодного. Третього стану немає. */
    data class Row(
        val id: String,
        val handle: String,
        val name: String,
        val compact: String,
    )

    /**
     * Форма відповіді для веба, і водночас межа, за яку довідник не переступає.
     *
     * Повертає рівно нуль або рівно один рядок — не тому, що сервер сьогодні
     * віддає один, а тому, що іншої гілки тут не написано. Список людей ніде
     * не збирається, тож і витекти йому нема звідки.
     */
    fun rows(handle: String, found: PeerInvite.Invite?, compact: String): List<Row> {
        val name = normalise(handle) ?: return emptyList()
        if (found == null) return emptyList()
        return listOf(
            Row(
                id = found.peerId,
                handle = name,
                name = found.name,
                compact = compact,
            ),
        )
    }

    /**
     * Сервер приймає обидві абетки base64, телефон шле звичайну (з '/' і '+'),
     * а підпис у відповіді приходить у base64url. Читаємо обидві, бо інакше
     * робочий запис відмовляв би через розкладку алфавіту.
     */
    private fun unB64(text: String): ByteArray? = runCatching {
        val body = text.trim().replace('-', '+').replace('_', '/').trimEnd('=')
        Base64.getDecoder().decode(body + "=".repeat((4 - body.length % 4) % 4))
    }.getOrNull()
}
