package local.phantom.companion.core.net.peer

/**
 * Дзвінок на дроті.
 *
 * Живий дзвінок веде ОДИН рід — [SIGNAL] (`PH-CAS:`). Ним їде тіло, яке склав
 * рушій WebRTC у вебі, цілим: пропозиція, відповідь, кандидат, «поклав». Усе,
 * що телефон з ним робить, — везе запечатаним листом і віддає рушієві на тому
 * боці. Своєї машини станів WebRTC тут немає й не буде: вона є у вебі, і друга
 * така розійшлася б із нею на першому ж перезбиранні бандла.
 *
 * Чому SDP їде тут, а не окремою сигнальною службою: служби, яка звела б два
 * телефони, не існує. Телефон не тримає HTTP-сервера, а `/inbound` на ПК-вузлі
 * приймає лише від відомого вузла. Дорога `send → seal → envelope → open` уже
 * доведена наскрізь, і кадр у тілі листа успадковує від неї підпис, шифрування
 * та реєстр, не додаючи жодного нового слухача. Наслідок варто назвати вголос:
 * підміняти SDP нема кому, тож окремого відбитка DTLS кадр не несе — довірений
 * канал і є той самий, яким їде сам SDP.
 *
 * Чотирьох рідних кадрів (`PH-CAL:`, `PH-CAA:`, `PH-CAX:`, `PH-CAE:`) тут
 * більше немає, і це рішення, а не прибирання. Вони були з того самого
 * задуму — «запрошення», «відповів», «скасував», «поклав» поруч із кімнатою, —
 * і [SIGNAL] заступив кожен із них ОДИН В ОДИН: `offer` замість запрошення,
 * `answer` замість відповіді, `hangup` із полем `reason` замість скасування й
 * кінця. Писаря їм не додали жодного разу за весь їхній вік, а питання «чия
 * поверхня дзвінка» відповідь має: ВЕБ. У зібраному бандлі стоїть повний
 * рушій (`getUserMedia`, `addTrack`, `createOffer`, екран із «взяти/
 * відхилити»), рідного екрана дзвінка в дереві немає, і другого не буде.
 * Тримати поруч із живим родом чотири мертві означало б, що наступний
 * упишеться в них — і розійдеться з рушієм, який таких слів не знає.
 *
 * Впізнавати їх на вході теж більше нема кому: `PH-CA*` не знає ні котлін, ні
 * бандл (заміряно грепом по зібраному вебу), а набране людиною тіло з машинною
 * позначкою все одно не стає карткою — його тримає спільний заслін
 * [PeerFrames.MARK], а не рід у реєстрі.
 */
object PeerCall {

    /**
     * Єдиний кадр дзвінка: домовляння звуку — SDP і кандидати ICE.
     *
     * Донедавна на його місці стояв `POST` на
     * `/api/v1/messenger/call/inbound` — адресу, якої на тому кінці не слухає
     * ніхто: єдиний слухач телефона ([PeerLink]) читає заголовок PHANTOM і
     * мовчки кидає все інше. Тобто ЖОДЕН дзвінок не доходив до другого апарата
     * взагалі, і провалювався він ще до того, як хтось згадає про звук.
     *
     * Кадр їде ЛИШЕ прямою дорогою, і заперечення тут про СХОВОК: лист лежить
     * там до семи діб, і возити ним обмін ICE означало б дзвінок, який
     * домовляється годину. Пряма дорога — це той самий Wi-Fi і той самий сокет,
     * яким летить слово: обмін коштує мілісекунди. Немає прямої дороги — немає
     * дзвінка, і про це кажуть уголос, а не кладуть SDP у сховок «на потім».
     *
     * Тіло — base64, а не сирий SDP: SDP несе переводи рядків і крапки з комою,
     * тобто рівно ті два знаки, на яких тримається цей кодувальник.
     */
    internal const val SIGNAL = "PH-CAS:"
    private const val SEP = ';'

    /**
     * Скільки апарат дзвонить, перш ніж сказати «не взяли».
     *
     * Межа потрібна з обох кінців: без неї апарат, чий співрозмовник вимкнувся
     * посеред виклику, дзвенів би, доки хтось не натисне, а той, хто набрав,
     * дивився б на «набираю» до ранку. Хвилина — і далі [PeerCallLine.expire]
     * кладе лінію та шле «no-answer» назад.
     *
     * Це межа ДЗВОНІННЯ, не РОЗМОВИ: [PeerCallLine.expire] чіпає лише
     * [PeerCallLine.Line.Dialing] і [PeerCallLine.Line.Ringing]. Щойно лінія
     * стає [PeerCallLine.Line.Talking], та сама функція повертає `null`
     * незалежно від того, скільки часу минуло, — перевірено на роках, не лише
     * на хвилинах ([PeerCallLineTest]). Стелі тривалості розмови в телефоні
     * немає: далі говорить рушій у вебі, і кладе слухавку лише людина.
     */
    const val RING_LIFE_MS = 60_000L

    /**
     * Стеля тіла сигналу в base64.
     *
     * Не з ощадливості: [PeerWire.MAX_BODY_BYTES] — 64 КіБ на ВЕСЬ кадр, а
     * навколо цього тіла стане ще конверт (`+33 %` від шифротексту в base64) і
     * підпис. Пропозиція SDP з відео — це 3-4 КіБ, кандидат — сотня байтів;
     * 16 384 знаків (12 КіБ сирих) лишають десятикратний запас і при цьому
     * відмовляють ДО сокета. Кадр, зрізаний на дроті, не відмовляється — він
     * мовчки не доїжджає, а дзвінок просто «не дзвонить».
     */
    const val MAX_SIGNAL_CHARS = 16_384

    /**
     * Що саме домовляється — і словами РУШІЯ, а не своїми.
     *
     * Перелік не вигаданий: це рівно ті пʼять слів, які зібраний веб-месенджер
     * ставить у `POST /messenger/call/<рід>` і які читає його ж
     * `window.__phantomCallSignal`. Своя назва поруч із його назвою була б
     * другою правдою про той самий кадр — і розійшлась би на першому ж
     * перезбиранні бандла.
     *
     * Доля в них різна, і саме тому рід їде окремо від тіла: пропозицію треба
     * ПОКАЗАТИ людині (і підняти апарат), відповідь — приставити до живого
     * дзвінка, кандидата — додати мовчки й пізніше за опис, «поклав» — погасити
     * плашку.
     */
    enum class Signalling(val mark: String, val webKind: String) {
        OFFER("o", "offer"),
        ANSWER("a", "answer"),
        ICE("i", "ice"),
        HANGUP("h", "hangup"),
        RADIO("r", "radio"),
        ;

        companion object {
            fun of(mark: String): Signalling? = entries.firstOrNull { it.mark == mark }

            /**
             * Слово, яким це називає веб. Закритий словник: рід, якого тут
             * немає, НЕ їде — замість того, щоб поїхати чимось іншим і
             * мовчки стати не тим кадром на тому кінці.
             */
            fun ofWeb(kind: String): Signalling? = entries.firstOrNull { it.webKind == kind }
        }
    }

    /**
     * [payload] — тіло, яке склав рушій WebRTC у вебі, слово в слово.
     *
     * Дріт його не читає й не має читати: рід кадру — єдине, від чого тут
     * залежить поведінка, а зміст належить рушію на обох кінцях. Саме тому
     * воно возиться ЦІЛИМ: телефон, який розбирав би SDP на поля й складав
     * назад, був би третьою правдою про формат, з якою рушій рано чи пізно
     * розійшовся б.
     */
    data class Signal(val callId: String, val what: Signalling, val payload: String)

    // ── складання ────────────────────────────────────────────────────────

    /**
     * Null — коли тіло порожнє або не влазить у [MAX_SIGNAL_CHARS]. Обидві
     * відмови видимі викликачеві ДО сокета: інакше дзвінок «просто не дзвонить».
     */
    fun encodeSignal(signal: Signal): String? {
        if (!isCallRef(signal.callId)) return null
        if (signal.payload.isEmpty()) return null
        val body = java.util.Base64.getEncoder().withoutPadding()
            .encodeToString(signal.payload.toByteArray(Charsets.UTF_8))
        if (body.length > MAX_SIGNAL_CHARS) return null
        return SIGNAL + signal.callId + SEP + signal.what.mark + SEP + body
    }

    // ── читання ──────────────────────────────────────────────────────────

    /**
     * Кадр дзвінка. Ним мовчать шторка й стрічка розмови.
     *
     * Імʼя ширше за єдиний рід навмисно: так його читають ті пʼять місць, які
     * ним користуються ([PeerMesh], [PeerOutbox]), і питання там саме таке —
     * «це дзвінок?», а не «це який із кадрів дзвінка?». Другого предиката з
     * тим самим тілом поруч не стоїть: одна умова — одне імʼя.
     */
    fun isCall(body: String): Boolean = body.startsWith(SIGNAL)

    /**
     * Тіло сигналу розбирається САМЕ ТУТ, а не в того, хто його показує:
     * base64 з дроту може бути чим завгодно, і місце, де він стає рядком, має
     * бути одне. Порожнє тіло — це не сигнал, а `null`, як і покалічене.
     */
    fun decodeSignal(body: String): Signal? {
        if (!isCall(body)) return null
        val parts = body.removePrefix(SIGNAL).split(SEP)
        if (parts.size != 3) return null
        val callId = parts[0].takeIf(::isCallRef) ?: return null
        val what = Signalling.of(parts[1]) ?: return null
        val raw = parts[2].takeIf { it.isNotEmpty() && it.length <= MAX_SIGNAL_CHARS } ?: return null
        val payload = runCatching {
            String(java.util.Base64.getDecoder().decode(raw), Charsets.UTF_8)
        }.getOrNull()?.takeIf { it.isNotEmpty() } ?: return null
        return Signal(callId, what, payload)
    }

    // ── дрібне ───────────────────────────────────────────────────────────

    /**
     * Номер дзвінка в кадрі сигналу — ЧУЖИЙ: його мінить рушій у вебі, і він
     * не шістнадцятковий (`call_9f31ac2b-17`, не `a1b2c3d4e5f60718`). Тому тут
     * не звірка з власним алфавітом, а межа набору й довжини: усе, крім
     * розділювача й того, що зламало б кадр. Вужче не можна — тоді дзвінки веба
     * не поїхали б узагалі; ширше не варто — тоді в кадр можна було б вкласти
     * другий кадр.
     */
    internal fun isCallRef(value: String): Boolean =
        value.length in 1..64 &&
            value.all { it in '0'..'9' || it in 'a'..'z' || it in 'A'..'Z' || it == '-' || it == '_' }
}
