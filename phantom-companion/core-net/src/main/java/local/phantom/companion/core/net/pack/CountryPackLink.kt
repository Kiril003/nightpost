package local.phantom.companion.core.net.pack

/**
 * Той самий фетчер пакiв країн, що й у `:app`, — видимий поверхням, які `:app`
 * не бачать.
 *
 * Дзеркало [WorldPackLink]: `AppContainer` кладе сюди свій екземпляр на старті,
 * а картка «Хмарні пакети» в `:feature-precision` бере його звідси.
 *
 * ЧОМУ НЕ ЗІБРАТИ ДРУГИЙ ФЕТЧЕР ПРЯМО В КАРТЦІ. Пак країни ставиться через
 * `CountryPackStore`, а той володіє КАТАЛОГОМ на диску: вистоюванням,
 * підміною каталогу одним rename і памʼяттю про версії. Другий екземпляр над
 * тим самим каталогом — це два писарі в одну теку, і перший же збіг у часі
 * лишив би пак напівпідмінений. Один фетчер на процес — не охайність, а
 * єдиний спосіб не мати двох.
 *
 * `null` (типовий стан, доки `:app` не назвався) означає «пакети країн звідси
 * не ставляться», а не «постав абияк»: та сама постава, що й у порожнього
 * ключа у [WorldPackLink].
 */
object CountryPackLink {
    @Volatile
    var fetcher: () -> PackFetcher? = { null }
}
