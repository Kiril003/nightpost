package local.phantom.companion.core.net.peer

/**
 * Кого цей телефон більше не слухає.
 *
 * Це ПРИЙМАЧ, а не екран. Кнопка, що ховає листи на показі, поки телефон їх
 * приймає, розшифровує, кладе в журнал, рахує в непрочитані й будить шторку, —
 * найгірша напівправда, яку тут можна поставити: людина вважає, що її більше
 * не дістають, а її телефон далі носить у кишені все, що та людина пише. Тому
 * рішення живе тут, на вході, і відповідь на заблокований кадр — та сама, що й
 * на кадр, який не відчинився: нічого.
 *
 * ТРИ речі, які тут навмисно НЕ робляться:
 *
 * 1. Нікому нічого не шлеться. Ані роду на дроті, ані поля в кадрі, ані
 *    окремої відмови — [PeerFrames.Kind] лишається без нового запису, і це
 *    перевірний факт, а не обіцянка. Блокування — місцеве рішення й МІСЦЕВА
 *    таємниця: щойно заблокований дізнається, що його заблокували, блокування
 *    стає знаряддям тиску, і людина перестає ним користуватись саме тоді, коли
 *    воно потрібне найбільше. З того боку це має виглядати як звичайна
 *    недоставка — телефон вимкнено, мережі немає, — і саме так і виглядає:
 *    квитанції немає, бо кадр не прийняли.
 *
 * 2. Нічого не стирається. Заблокований не «зникає» — його рядок і минула
 *    розмова лишаються, бо їх уже прийняли; нове просто не заходить. Стерти
 *    розмову — окрема дія з окремою ціною, і зшивати її з блокуванням означало
 *    б відбирати переписку в людини, яка просила тиші, а не забуття.
 *
 * 3. Рішення не залежить від роду кадру. Слово, вкладення, дзвінок, картка
 *    профілю, знайомство, домовляння ключа — усе від цієї людини. Рід кадру
 *    тут навіть не питають: питають, ХТО його склав, а це єдине поле, яке
 *    дороги [refusesEnvelope], [refusesHello] і [refusesIntro] читають до
 *    будь-якої арифметики на чужу користь.
 *
 * Хто відправник, у трьох дверей написано по-різному, і жодні з них тут не
 * розбираються вдруге: кожна питає той самий обʼєкт, що цей кадр і складає.
 */
object PeerBlock {

    /**
     * Скільки імен носити. Це не політика — це стеля памʼяті: список їде в
     * кожен вхідний кадр, і він мусить лишатись коротким рядком на диску.
     * ОБРАНО, НЕ ВИМІРЯНО: ніхто не бачив телефона, де заблокованих більше.
     */
    const val MAX_KEPT = 512

    /** Порожній рядок не блокує нікого: інакше кадр без відправника — заблокований. */
    fun blocks(blocked: Set<String>, id: String): Boolean =
        id.isNotBlank() && id in blocked

    /** Додати. Двічі одне й те саме — той самий список, не другий рядок. */
    fun block(blocked: Set<String>, id: String): Set<String> {
        if (id.isBlank()) return blocked
        if (id in blocked) return blocked
        if (blocked.size >= MAX_KEPT) return blocked
        return blocked + id
    }

    /** Зняти. Усе повертається таким, яким було: тут нема чого воскрешати. */
    fun unblock(blocked: Set<String>, id: String): Set<String> =
        if (id in blocked) blocked - id else blocked

    /**
     * Запечатаний лист із дроту або зі сховка.
     *
     * Читає ЛИШЕ адресування, яке і так відкрите для будь-кого на тій самій
     * мережі, і не торкається ключів: заблокований не платить нам жодного
     * розшифрування. Кадр, який не розібрався, не заблокований — він просто не
     * кадр, і з ним розмовляє той, хто його читає далі.
     */
    fun refusesEnvelope(blocked: Set<String>, raw: String): Boolean {
        if (blocked.isEmpty()) return false
        val from = PeerEnvelope.parse(raw)?.from ?: return false
        return blocks(blocked, from)
    }

    /**
     * Вітання, яким домовляються про ключ зустрічі.
     *
     * Відмова саме тут, а не після [PeerSession.answer], — це відмова ДО
     * арифметики: заблокований не отримує ані ключа, ані процесорного часу, і
     * не має жодного способу побачити різницю між нами й телефоном, який
     * вимкнули. Без ключа зустрічі його дальші листи не відчиняться взагалі.
     */
    fun refusesHello(blocked: Set<String>, raw: String): Boolean {
        if (blocked.isEmpty()) return false
        val from = PeerSession.parse(raw)?.from ?: return false
        return blocks(blocked, from)
    }

    /**
     * Знайомство у зворотний бік.
     *
     * Без цих дверей блокування було б виставою: заблокований має наш код, і
     * [PeerIntro] впускає всякого, хто його бачив, — він вписав би себе назад
     * наступним кадром разом зі свіжою адресою. Той самий засув, що в
     * прибраного (`isDeclined`), і з тієї ж причини.
     */
    fun refusesIntro(blocked: Set<String>, raw: String): Boolean {
        if (blocked.isEmpty()) return false
        val from = PeerIntro.parse(raw)?.from ?: return false
        return blocks(blocked, from)
    }

    /**
     * Відчинений лист — останні двері.
     *
     * Потрібні, бо сховок віддає листа вже розібраним: там немає сирого кадру,
     * який можна було б віддати [refusesEnvelope].
     */
    fun refuses(blocked: Set<String>, message: PeerMessage): Boolean =
        blocks(blocked, message.fromId)
}
