package local.phantom.companion.feature.stream.ui.map

import java.io.File
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Test

/**
 * Коло сумніву має межу на ЕКРАНІ, не лише в метрах.
 *
 * **Вирок власника 31.08:** «бісить вигляд всього у мапі, маршрути, а ці великі
 * овали тупі ну і вибішує». Порахував на його полотні (411 dp завширшки, смуга
 * масштабу 500 м ≈ 88 dp):
 * ```
 * сумнів  300 м → овал 106 dp = чверть ширини екрана
 * сумнів  500 м → овал 176 dp = пів екрана
 * сумнів 1500 м → овал 528 dp = ширше за екран
 * ```
 * Овал виростає рівно тоді, коли фікс поганий — у приміщенні, у дворі, під
 * глушінням. Тобто в щоденних умовах, а не в рідкісних.
 *
 * **Стеля `HALO_DISPLAY_MAX_M` (1500 м) від цього не рятувала: вона в метрах, а
 * болить у пікселях.** На міському зумі 1500 м — це ширше за екран.
 *
 * **Чому межа не є приховуванням правди.** Коло чесне доти, доки читається як
 * ПЛОЩА. Перерісши третину екрана, воно перестає казати «ось наскільки я не
 * певен» і починає казати «із застосунком щось не так» — тобто перестає бути
 * інформацією і стає шумом. Величину сумніву несе число у смузі довіри: воно не
 * бреше й не займає пів екрана. Це та сама операція, яку дім робив уже двічі —
 * перенести правду з форми в СЛОВО.
 *
 * **Чого цей сторож НЕ стереже, і це важливо:** заливку кола. Вона тут
 * **свідома** — `MapOverlayLayers` пояснює, що диск колись прибрали, а тоненький
 * шепіт (≤0.10) повернули навмисно, щоб кільце не читалось як смуга дороги. Я
 * мало не зняв її як «скасоване рішення» і зупинився, прочитавши той коментар.
 *
 * **Сліпа пляма:** тест читає джерело, а не малює коло. Він побачить, що межу
 * прибрали, і не побачить, що її зробили неправильною.
 */
class TrustHaloScreenCapTest {

    private fun source(): String {
        var dir: File? = File("").absoluteFile
        while (dir != null && !File(dir, "feature-stream").isDirectory) dir = dir.parentFile
        val root = dir ?: fail("корінь репозиторію не знайдено") as Nothing
        val f = File(
            root,
            "feature-stream/src/main/java/local/phantom/companion/feature/stream/ui/map/MapCameraLoop.kt",
        )
        assertTrue("MapCameraLoop.kt зник — сторож більше нічого не стереже", f.isFile)
        return f.readText()
    }

    @Test
    fun `радіус гало обмежений розміром екрана, а не лише метрами`() {
        val src = source()
        assertTrue(
            "у MapCameraLoop немає межі, виведеної з metersPerPixel — коло знову росте в " +
                "пікселях без стелі. Стеля в метрах (HALO_DISPLAY_MAX_M) від овала не рятує: " +
                "на міському зумі 1500 м ширші за екран.",
            src.contains("metersPerPixel") && src.contains("widthPixels"),
        )
        assertTrue(
            "радіус більше не обмежується екранною межею — шукав coerceAtMost(onScreenCapM)",
            Regex("""coerceAtMost\(\s*onScreenCapM\s*\)""").containsMatchIn(src),
        )
    }

    /**
     * ДОКАЗ, що межа справді кусає саме там, де боліло: на міському зумі
     * поганий фікс мусить бути обрізаний, а добрий — ні.
     */
    @Test
    fun `межа ріже поганий фікс і не чіпає доброго`() {
        // z15 ≈ місто; широта Києва. metersPerPixel — та сама функція, що годує смугу масштабу.
        val mpp = metersPerPixel(50.45, 15.0)
        val capM = mpp * 1080 / 6.0

        assertTrue(
            "добрий фікс (30 м) не сміє обрізатись: межа $capM м",
            30.0 <= capM,
        )
        assertTrue(
            "поганий фікс (1500 м) мусить обрізатись: межа $capM м",
            1500.0 > capM,
        )
    }
}
