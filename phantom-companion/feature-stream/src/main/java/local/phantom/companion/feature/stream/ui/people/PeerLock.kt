package local.phantom.companion.feature.stream.ui.people

/**
 * Коли розмову з людьми треба замикати наново.
 *
 * ⚠ **Цю політику зараз не викликає НІХТО.** Вона була видалена з дерева разом
 * зі своїм місцем виклику, а тест на неї лишився — тобто безпекове правило
 * зникло тихо, і єдиним слідом був червоний компілятор у тестах. Обʼєкт
 * відновлено дослівно за тим тестом, щоб правило не загубилось; але поки його
 * ніхто не питає, замок не працює. Це не «є контроль» — це «є формула».
 *
 * Правило саме по собі: згаслий екран — це і «відклав», і «мене зупинили», тож
 * він замикає негайно й без пільги. Перехід у інший застосунок і назад —
 * звичайна робота однією рукою, і на неї є [GRACE_MS].
 */
object PeerLockPolicy {

    /** Скільки живе пільга на стрибок у сусідній застосунок. */
    const val GRACE_MS = 15_000L

    fun relocks(leftAtMs: Long, screenOnAtStop: Boolean, nowMs: Long): Boolean =
        !screenOnAtStop || (nowMs - leftAtMs) >= GRACE_MS
}
