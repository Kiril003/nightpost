package local.phantom.companion.feature.stream.ui.map.atlas

/**
 * ATLAS-2 — як бюджет [LensFrame.budget] нарешті кусається.
 *
 * До цієї хвилі бюджети були числами, яких ніхто не читав: таблиця казала
 * «дванадцять місць за кермом», а джерело клало на землю всі тисячу й лишало
 * розрідження движку. Движок робить це чесно, але СЛІПО — він знає тільки, що
 * два диски перетнулись, і не знає, що один із них аптека.
 *
 * Тому проріджування живе тут, у побудові джерела, і має рівно один закон:
 * **менший ключ виживає**. Ключ дає сам внесок (у місць це ярус піна, той
 * самий, що вже стоїть у `symbolSortKey`), а не цей файл — інакше зʼявився б
 * другий список критичності, який неминуче розійшовся б із першим.
 *
 * Порядок стабільний: рівні ключі лишаються в тому порядку, в якому прийшли, а
 * приходять вони вже проранжованими. Тож між двома кадрами з тими самими
 * даними на екрані стоять ті самі точки — мигання «то є, то нема» тут
 * структурно неможливе.
 */
internal object DensityBudget {

    /** Перші [budget] за ключем; [LensFrame.UNLIMITED] проходить сюди як стеля. */
    fun <T> trim(items: List<T>, budget: Int, key: (T) -> Int): List<T> {
        if (budget >= items.size) return items
        if (budget <= 0) return emptyList()
        return items.asSequence()
            .withIndex()
            .sortedWith(compareBy({ key(it.value) }, { it.index }))
            .take(budget)
            .sortedBy { it.index }
            .map { it.value }
            .toList()
    }
}
