package local.phantom.companion.feature.stream.ui.map.icons

// Знаки КЕРУВАННЯ мапою. Числа — одиниці сітки 24×24 (GlyphGrid),
// живе поле 2..22; y росте вниз.
//
// Навіщо ця родина взагалі зʼявилась. Реєстр [PhantomGlyph] у своєму KDoc
// стверджує: «жодного іншого джерела гліфів у мапи нема: ні системного емодзі,
// ні шрифту, ні drawable». На даних це було правдою — пін укриття, загрози,
// транспорту вже носили нашу руку. А дека, орби й капсули — тобто рівно те, чим
// людина цією мапою КОРИСТУЄТЬСЯ — лишались на стокових `material.icons`:
// заміряно 30.08, 131 імпорт на поверхні мапи, 0 власних у деці.
//
// Тобто хворобу, яку та родина й лікувала («разом вони читались як набір
// наліпок, а не як мапа»), вилікували на даних і не помітили на контролях.
// Ці вісім знаків закривають дужку: одна рука на всю мапу — і на те, що вона
// показує, і на те, чим її гортають.

/**
 * Шари: три пластини одна під одною.
 *
 * Верхня — контуром, дві нижні — самими лише гребенями. Три однакові ромби
 * читались би як стос паперу; тут видно, що горішня «активна», а решта лежить
 * під нею — саме те, що робить перемикач шарів.
 */
internal fun GlyphPen.layers() {
    polyClosed(12f, 2.6f, 21f, 7.4f, 12f, 12.2f, 3f, 7.4f)
    poly(4.4f, 10.6f, 12f, 14.6f, 19.6f, 10.6f)
    poly(4.4f, 14.4f, 12f, 18.4f, 19.6f, 14.4f)
}

/**
 * Основа: складений аркуш мапи, три панелі на двох згинах.
 *
 * Питання цієї кнопки — «з чого намальована сама земля», тому знак говорить
 * про ПАПІР, а не про місце. Плаский прямокутник читався б як картка, а
 * складений аркуш ні з чим більше на цій деці не плутається.
 */
internal fun GlyphPen.ground() {
    polyClosed(
        2.8f, 6.2f, 9f, 3.6f, 15f, 6.6f, 21.2f, 4f,
        21.2f, 17.8f, 15f, 20.4f, 9f, 17.4f, 2.8f, 20f,
    )
    line(9f, 3.6f, 9f, 17.4f)
    line(15f, 6.6f, 15f, 20.4f)
}

/**
 * Пакети землі: скриня, і стрілка, що лягає в неї.
 *
 * Не хмара. Хмара означає «взяти з мережі», а кнопка означає протилежне:
 * покласти шматок землі СОБІ, щоб він лишився без мережі.
 *
 * **Перемальовано після скла 31.08.** Перша спроба була плитка + стрілка +
 * полиця: на 20 dp полиця читалась як підкреслення, а знак загалом — як
 * «експортувати». Тепер носій сенсу один і він силуетний — **скриня**, те саме
 * слово, яким продукт уже називає своє сховище. Трапеція ширша вгорі читається
 * як посудина навіть на 16 dp, а стрілка, що входить у неї, не лишає напрямку
 * на здогад.
 */
internal fun GlyphPen.packs() {
    polyClosed(3.4f, 12.4f, 20.6f, 12.4f, 19f, 20.6f, 5f, 20.6f)
    line(3.4f, 15.4f, 20.6f, 15.4f)
    line(12f, 2.6f, 12f, 10.4f)
    poly(8.8f, 7.2f, 12f, 10.4f, 15.2f, 7.2f)
}

/**
 * Компас: кільце і стрілка-ромб.
 *
 * Ромб, а не голка під кутом: голка в колі — знак «дослідити» в чужій мові, а
 * тут кнопка означає «поверни північ угору». Симетричний ромб читається як
 * прилад, і його поворот на екрані видно навіть краєм ока.
 */
internal fun GlyphPen.compass() {
    circle(12f, 12f, 8.8f)
    solid(12f, 5.6f, 14.8f, 12f, 12f, 18.4f, 9.2f, 12f)
}

/**
 * Азимут: дротик, що вказує РІВНО в один бік — на відміну від симетричного
 * ромба [compass], тут поворот на конкретний кут читається однозначно (180°
 * від самого себе виглядає інакше). Потрібен там, де маршруту немає взагалі
 * і єдина чесна відповідь — «туди, по прямій»: стрілка повертається на сам
 * азимут, а не лишає це рядку дрібного тексту, який суд 06.09 знайшов
 * зрізаним поруч із кнопкою закриття.
 */
internal fun GlyphPen.bearing() {
    solid(12f, 3f, 18f, 20f, 12f, 15f, 6f, 20f)
}

/**
 * Де я: приціл із повним кільцем і живим ядром.
 *
 * Стан «позиція є і камера йде за мною». Ядро суцільне — це єдиний стан із
 * трьох, у якому мапа щось про людину ЗНАЄ.
 */
internal fun GlyphPen.locateLocked() {
    circle(12f, 12f, 6.2f)
    dot(12f, 12f, 1.9f)
    line(12f, 2.6f, 12f, 5f)
    line(12f, 19f, 12f, 21.4f)
    line(2.6f, 12f, 5f, 12f)
    line(19f, 12f, 21.4f, 12f)
}

/**
 * Шукаю небо: те саме кільце, але РОЗІРВАНЕ, ядро дрібне.
 *
 * Розрив несе весь сенс: людина бачить, що прилад працює й ще не має відповіді.
 * Це той самий стан, який рушій позиції довго плутав із «глушінням» — знак не
 * має права називати пошук нападом.
 */
internal fun GlyphPen.locateSeeking() {
    arc(12f, 12f, 6.2f, -60f, 120f)
    arc(12f, 12f, 6.2f, 120f, 120f)
    dot(12f, 12f, 1.2f)
    line(12f, 2.6f, 12f, 5f)
    line(12f, 19f, 12f, 21.4f)
    line(2.6f, 12f, 5f, 12f)
    line(19f, 12f, 21.4f, 12f)
}

/**
 * Неба немає: приціл, перекреслений однією рискою.
 *
 * Без ядра — показувати нічого. Риска йде через усе поле, а не через саме
 * кільце: перекреслене кільце читається як «вимкнено рукою», а тут вимкнув не
 * користувач.
 */
internal fun GlyphPen.locateBlind() {
    circle(12f, 12f, 6.2f)
    line(4.4f, 4.4f, 19.6f, 19.6f)
    line(12f, 2.6f, 12f, 5f)
    line(2.6f, 12f, 5f, 12f)
}

/**
 * Згорнути: шеврон угору.
 *
 * Стрілка, а не хрестик: аркуш не закривається назавжди, він лягає назад у
 * свою кнопку. Хрестик обіцяв би, що зникне разом зі станом.
 */
internal fun GlyphPen.collapse() {
    poly(4.6f, 15.4f, 12f, 8f, 19.4f, 15.4f)
    line(4.6f, 20.4f, 19.4f, 20.4f)
}
