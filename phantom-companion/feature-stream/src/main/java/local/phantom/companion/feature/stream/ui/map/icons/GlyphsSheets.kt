package local.phantom.companion.feature.stream.ui.map.icons

// Знаки АРКУШІВ мапи. Числа — одиниці сітки 24×24 (GlyphGrid),
// живе поле 2..22; y росте вниз.
//
// Що це за партія. 30.08 дека й орби перейшли на власну руку (GlyphsControls.kt),
// і стеля стокових імпортів упала 131 → 123. Решта 123 сиділа не рівним шаром:
// два файли несли 27 з них — `SheetHost.kt` (17) і `MapCommandSheet.kt` (10).
// Це аркуші: те, що відкривається під пальцем після тапу по мапі, і смуга
// маршруту. Тобто друга за гучністю поверхня після деки — і вся чужою рукою.
//
// Чим ця партія відрізняється від контролів. Дека питає «яка мапа»; аркуш
// питає «що я роблю з ЦІЄЮ точкою». Тому тут майже немає знаків-предметів і
// майже всі — знаки ДІЇ, а дію легше за все перекласти з чужої мови й не
// помітити підміни. Правило партії просте: спершу питаємо, що кнопка означає в
// PHANTOM, і аж тоді малюємо. Через це нитка маршруту гнеться під прямим кутом
// (наш маршрут іде графом доріг, а не по прямій), ізохрона має той самий
// нерівний обрис, який кнопка й малює на склі, а «обліт» носить камеру, а не
// літак — літак у цій родині вже зайнятий ворожою авіацією (`JET`).
//
// Шість стокових значків цих двох файлів не потребували нового малюнка взагалі:
// патруль → POLICE, блокпост → CHECKPOINT, ДТП → ACCIDENT, пальне → FUEL,
// авто → CAR, автобус → BUS. Родина вже мала їх на даних — їх просто ніхто не
// покликав на кнопки.

/* ── Маршрут: прокласти, провести крізь точку, рушити, оглянути ─────────── */

/**
 * Маршрут сюди: нитка від оператора до цілі.
 *
 * Нитка гнеться під ПРЯМИМ кутом, а не йде по діагоналі. Це не орнамент: наш
 * маршрут рахується A* по графу доріг у кишені, і пряма стрілка обіцяла б
 * політ по повітрю — рівно те, чого продукт не робить. Залита крапка — «я»,
 * кільце з ядром — мета.
 *
 * Відкинуто компас (`Icons.Outlined.Explore`, і наш власний `COMPASS`): на деці
 * компас уже означає «поверни північ угору». Дві різні кнопки під одним
 * силуетом — це та сама різнорукість, тільки навпаки.
 */
internal fun GlyphPen.routeTo() {
    dot(4.6f, 19.4f, 1.8f)
    poly(4.6f, 19.4f, 4.6f, 13.4f, 12.4f, 13.4f, 12.4f, 7.4f, 15.6f, 7.4f)
    circle(18.6f, 7.4f, 3f)
    dot(18.6f, 7.4f, 1.2f)
}

/**
 * Звідси маршрут: та сама нитка, але кільце з ядром стоїть НА ПОЧАТКУ — ця
 * точка вже названа, — а кінець лишається порожнім кільцем: куди, скаже
 * наступний дотик. Дзеркало routeTo, не новий силует.
 */
internal fun GlyphPen.routeFrom() {
    circle(5.4f, 18.6f, 3f)
    dot(5.4f, 18.6f, 1.2f)
    poly(5.4f, 15.6f, 5.4f, 11.4f, 12.4f, 11.4f, 12.4f, 7.4f, 16.8f, 7.4f)
    circle(18.6f, 7.4f, 1.8f)
}

/**
 * Маршрут через цю точку: нитка, що ЗГИНАЄТЬСЯ крізь кільце.
 *
 * Відкинуто плюс. Плюс каже «додати ще один» — так, ніби точок стає більше;
 * насправді маршрут лишається один, він просто змінює форму, щоб пройти тут.
 * Знак показує саме це: та сама нитка, підважена посередині.
 *
 * Той самий силует носить рядок проміжної зупинки у смузі маршруту — це не
 * економія, це одна відповідь на одне питання: «крізь що йде нитка».
 */
internal fun GlyphPen.via() {
    poly(2.8f, 18.8f, 7.2f, 18.8f, 10.2f, 13.2f)
    circle(12f, 11.4f, 2.6f)
    dot(12f, 11.4f, 1.1f)
    poly(13.8f, 13.2f, 16.8f, 18.8f, 21.2f, 18.8f)
}

/**
 * Старт ведення: вістря, що стоїть на нитці й дивиться вперед.
 *
 * Відкинуто трикутник «плей». Тут нічого не програється й нічого не можна
 * поставити на паузу — рушає ЛЮДИНА, і рушає по конкретній нитці. Тому під
 * вістрям є дорога, і вістря стоїть у її кінці, а не в порожнечі.
 */
internal fun GlyphPen.guide() {
    poly(3.2f, 20.4f, 9.4f, 20.4f, 9.4f, 9.4f, 15.4f, 9.4f)
    solid(15.4f, 5.4f, 21f, 9.4f, 15.4f, 13.4f)
}

/**
 * Обліт: камера, що йде дугою над маршрутом.
 *
 * Відкинуто літак — і не за красу. У цій же родині літак уже намальовано
 * (`JET`), і там він означає ВОРОЖУ авіацію. Один силует на «подивитись згори»
 * і на «до нас летить» — не двозначність, а хибна тривога.
 *
 * Дуга — це шлях камери, пряма внизу — сам маршрут, конус — погляд, спрямований
 * на нього. Разом читається як огляд, а не як переліт.
 */
internal fun GlyphPen.flyover() {
    line(3.4f, 19.6f, 20.6f, 19.6f)
    arc(12f, 19.6f, 8.6f, 180f, 180f)
    solidBox(10.2f, 6.2f, 3.6f, 2.6f, 0.7f)
    solid(9.4f, 8.8f, 14.6f, 8.8f, 12f, 11.6f)
}

/* ── Профілі маршруту: чим саме людина поїде ───────────────────────────── */

/**
 * Пішки: два сліди, а не постать.
 *
 * У ряду профілів поруч стоять кузов авто й рама велосипеда — предмети. Постать
 * серед предметів читається як «пасажир», а не як спосіб руху; слід ноги
 * лишається в тому ж класі речей, що й колеса.
 *
 * Сліди зсунуті по діагоналі: два однакові поруч читались би як пара взуття у
 * вітрині, а зсув робить із них ХІД.
 */
internal fun GlyphPen.foot() {
    dot(8.4f, 5f, 1.1f)
    solidBox(6.2f, 6.6f, 4.4f, 7.6f, 2.2f)
    dot(15.6f, 10.2f, 1.1f)
    solidBox(13.4f, 11.8f, 4.4f, 7.6f, 2.2f)
}

/**
 * Вело: два колеса й рама між ними.
 *
 * Колеса навмисно порожні, без спиць: спиці вже несе `TYRE` (шиномонтаж), і на
 * 16 dp у сегменті профілю вони злипаються в сіру пляму. Кермо й сідло — по
 * одній рисці кожне: без них рама читалась як трикутник на двох кільцях.
 */
internal fun GlyphPen.bike() {
    circle(6.4f, 16.4f, 4.2f)
    circle(17.6f, 16.4f, 4.2f)
    poly(6.4f, 16.4f, 9.6f, 9.4f, 14.6f, 9.4f, 17.6f, 16.4f)
    line(8.2f, 9.4f, 11f, 9.4f)
    line(14.6f, 9.4f, 16.8f, 7.4f)
}

/* ── Питання до точки: мапа відповідає сама, або відповідає розмова ─────── */

/**
 * Що тут: питання, поставлене НАД конкретним місцем.
 *
 * Крапка знака питання — це ромб `PLACE`, тобто рідне «звичайне місце» родини.
 * Питання не висить у повітрі: воно стоїть на тій точці, яку людина щойно
 * притисла пальцем.
 *
 * Відкинуто зірочки «магії» (`Icons.Filled.AutoAwesome`). Блиск — чуже слово
 * для «це зробив ШІ», а на тактичній мапі блиск читається як спалах. Продукт
 * тут не показує фокус: він читає те, що вже лежить у кеші довкола точки.
 */
internal fun GlyphPen.whatHere() {
    arc(12f, 8.4f, 5f, 180f, 210f)
    poly(16.3f, 10.9f, 12f, 14.6f, 12f, 16.6f)
    solid(12f, 18.4f, 13.7f, 20.1f, 12f, 21.8f, 10.3f, 20.1f)
}

/**
 * Запитати про це: репліка, чий хвіст висить над позначеною точкою.
 *
 * Сусідній знак `WHAT_HERE` теж питає — і це різні дії, тому силуети різні:
 * «Що тут?» мапа відповідає сама й на місці, а ця кнопка виносить точку в
 * РОЗМОВУ. Звідси репліка.
 *
 * Хвіст навмисно не торкається крапки. Дотик робив би з двох знаків один
 * предмет; розрив каже, що розмова тільки ПРО цю точку, а живе в іншому місці.
 */
internal fun GlyphPen.askHere() {
    box(3.2f, 3.4f, 17.6f, 10.2f, 2.4f)
    solid(7.4f, 18.6f, 11.4f, 13.6f, 7.4f, 13.6f)
    dot(7.4f, 20.2f, 1.4f)
}

/* ── Точка йде назовні: у чужу мапу або в чужі руки ─────────────────────── */

/**
 * Відкрити в чужих картах: стрілка, що виходить крізь ВІДКРИТИЙ кут нашої рамки.
 *
 * Рамка не замкнена навмисно — верхній правий кут зрізано, і саме туди йде
 * стрілка. Це не «нове вікно» (`Icons.AutoMirrored.Outlined.OpenInNew`): у
 * PHANTOM нема вкладок, які можна відкрити. Є межа власного аркуша, за якою
 * земля вже не наша, і кнопка означає рівно перетин цієї межі.
 */
internal fun GlyphPen.handoff() {
    poly(15.4f, 4.2f, 4.2f, 4.2f, 4.2f, 19.8f, 19.8f, 19.8f, 19.8f, 8.6f)
    line(11.6f, 12.4f, 20.6f, 3.4f)
    poly(15.2f, 3.4f, 20.6f, 3.4f, 20.6f, 8.8f)
}

/**
 * Поділитись: залите джерело і два порожні вузли, до яких ідуть нитки.
 *
 * Три ОДНАКОВІ вузли (як у стокового «share») не кажуть, хто кому дає — з них
 * так само читається «синхронізація» або «мережа». Тут джерело залите, а
 * одержувачі порожні, тож напрямок видно без підпису: координати йдуть від
 * мене, а не до мене.
 */
internal fun GlyphPen.handout() {
    dot(4.6f, 12f, 2.2f)
    circle(18.4f, 5.6f, 2.6f)
    circle(18.4f, 18.4f, 2.6f)
    line(6.6f, 10.8f, 16.2f, 6.6f)
    line(6.6f, 13.2f, 16.2f, 17.4f)
}

/* ── Що мапа малює у відповідь ──────────────────────────────────────────── */

/**
 * Скільки встигну дійти: сам обрис досяжності й точка, з якої його рахували.
 *
 * Знак — це буквально те, що кнопка кладе на скло. Обрис навмисно НЕРІВНИЙ:
 * коло обіцяло б однакову досяжність на всі боки, а вона однакова лише в
 * полі — у місті її ріже забудова, річка й міст, і саме ця нерівність є
 * відповіддю.
 *
 * Відкинуто постать, що йде (`Icons.AutoMirrored.Outlined.DirectionsWalk`): вона
 * каже «пішки», тобто СПОСІБ, а питання кнопки — «доки».
 */
internal fun GlyphPen.reach() {
    polyClosed(
        12f, 3.2f, 17.6f, 5.4f, 20.8f, 10.6f, 19.4f, 16.4f,
        14.2f, 20.4f, 8.2f, 20.2f, 3.6f, 16f, 2.8f, 10f, 6.6f, 5.2f,
    )
    dot(12f, 12f, 1.8f)
}

/**
 * Поле небезпеки: осердя і два кільця, що слабшають назовні.
 *
 * Осердя — трикутник, той самий, яким родина позначає небезпеку (`DANGER`).
 * Кільця розірвані, і зовнішнє розірване сильніше за внутрішнє: небезпека не
 * закінчується різко, вона згасає з відстанню — рівно те, що кнопка й
 * розливає по мапі з живих позначок.
 *
 * Відкинуто розсип крапок (`Icons.Outlined.BlurOn`). Крапки кажуть «нечітко»,
 * а поле не нечітке — воно ГРАДУЙОВАНЕ, і кожен його рівень має число.
 */
internal fun GlyphPen.dangerField() {
    solid(12f, 8.4f, 15.4f, 14.2f, 8.6f, 14.2f)
    arc(12f, 11.6f, 6.6f, -55f, 110f)
    arc(12f, 11.6f, 6.6f, 125f, 110f)
    arc(12f, 11.6f, 9.6f, -40f, 80f)
    arc(12f, 11.6f, 9.6f, 140f, 80f)
}

/* ── Власні місця оператора: лишити, переписати, викинути ───────────────── */

/**
 * Зберегти місце: пін, УТКНУТИЙ у землю.
 *
 * Продукт зберігає точку не «в список» — він лишає її собі на землі, щоб вона
 * була, коли мережі не буде. Тому під піном є риска землі: без неї лишається
 * просто крапля, а крапля в цій родині вже означає воду (`WATER`, вістрям
 * угору).
 *
 * Відкинуто стрічку-закладку (`Icons.Outlined.BookmarkBorder`): закладка — знак
 * ЧИТАНОГО, а тут нічого не читають. Відкинуто й зірку: зірка в родині вже
 * зайнята «улюбленим» (`STAR`), а зберігають не лише улюблене.
 */
internal fun GlyphPen.keep() {
    circle(12f, 8.6f, 4.6f)
    poly(8.4f, 11.2f, 12f, 17.8f, 15.6f, 11.2f)
    dot(12f, 8.6f, 1.6f)
    line(6.4f, 20.4f, 17.6f, 20.4f)
}

/**
 * Перейменувати: олівець, що пише ПО РЯДКУ.
 *
 * Рядок під олівцем несе весь сенс. Сам олівець означав би «малювати» — а на
 * мапі є чим малювати (геозони, позначки), і сплутати ці дві дії було б
 * дорого. Олівець над рядком може означати лише слово.
 *
 * Вістря залите окремим трикутником: у контурі олівець на 20 dp читався як
 * порожня планка.
 */
internal fun GlyphPen.rename() {
    polyClosed(9.2f, 14.6f, 17.4f, 6.4f, 19.8f, 8.8f, 11.6f, 17f)
    solid(9.2f, 14.6f, 11.6f, 17f, 8f, 18.2f)
    line(4f, 20.6f, 20f, 20.6f)
}

/**
 * Видалити місце: кошик із вічком і покришкою.
 *
 * Тут навмисно НЕ хрестик. На цьому ж аркуші хрестик уже означає «скасувати»
 * (`DISMISS`), і два різні за наслідком натиски — відмовитись від правки й
 * знищити збережену точку — не сміють носити один силует. Кошик — єдине в
 * родині, що каже «назовсім».
 *
 * Корпус звужений донизу: рівний прямокутник читався як коробка, тобто як
 * сховок, а не як його протилежність. Відкинуто вертикальні риски всередині —
 * на 20 dp вони злипаються в сіру пляму.
 */
internal fun GlyphPen.discard() {
    line(3.6f, 6.8f, 20.4f, 6.8f)
    poly(9.4f, 6.8f, 9.4f, 4.2f, 14.6f, 4.2f, 14.6f, 6.8f)
    poly(5.6f, 6.8f, 6.8f, 20.4f, 17.2f, 20.4f, 18.4f, 6.8f)
}

/* ── Дві відповіді, які людина дає аркушу ───────────────────────────────── */

/**
 * Підтвердити: галочка з коротким плечем.
 *
 * Коротке плече вдвічі коротше за довге і опускається нижче — інакше знак
 * вирівнюється в «менше». Кут навмисно гострий: тупа галочка на 22 dp
 * розпливається в дугу.
 *
 * Відкинуто дискету й скриню: у сховок тут нічого не кладеться, людина лише
 * каже «так, це те слово».
 */
internal fun GlyphPen.confirm() {
    poly(4.4f, 12.6f, 9.8f, 18.4f, 19.6f, 5.6f)
}

/**
 * Закрити, скасувати, прибрати: хрест.
 *
 * Один силует на три кнопки свідомо. Усі три означають одне — «того, що я почав,
 * не буде»: скасована правка назви, знята картка, прибрана зупинка. Нічого при
 * цьому не знищується назавжди — для «назовсім» у родині стоїть `DISCARD`.
 *
 * Відкинуто шеврон: шеврон у нас уже сказаний (`COLLAPSE` — «аркуш лягає назад у
 * свою кнопку»), а тут дія не відкладається, а відмовляється.
 */
internal fun GlyphPen.dismiss() {
    line(5.2f, 5.2f, 18.8f, 18.8f)
    line(18.8f, 5.2f, 5.2f, 18.8f)
}
