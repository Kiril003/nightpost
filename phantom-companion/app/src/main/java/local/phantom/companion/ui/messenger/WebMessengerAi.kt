package local.phantom.companion.ui.messenger

/**
 * Нейронка як співрозмовник у стрічці, а не як окремий екран.
 *
 * Тут живуть три речі, і всі три — чисті функції над рядком, без `org.json` і
 * без `android.*`: у модулі `app` юніт-тест бачить від `org.json` заглушку, яка
 * кидає на першому виклику. Тому те, що варто перевіряти, перевіряється
 * ЗНАЧЕННЯМ — так само, як у [WebMessengerKinds] і [WebMessengerGroups].
 *
 *  * [mentioned] — чи кликали модель у груповій розмові;
 *  * [ask] — що саме в неї спитали, без самого звертання;
 *  * [encode]/[said] — як її відповідь їде дротом, щоб на ЧУЖОМУ телефоні вона
 *    лишилась відповіддю моделі, а не рядком того, хто її переказав.
 */
internal object WebMessengerAi {

    /**
     * Позначка відповіді моделі в тілі листа.
     *
     * Починається з [local.phantom.companion.core.net.peer.PeerFrames.MARK], як
     * і всі машинні позначки продукту, але родом дроту НЕ є: `PeerFrames.kindOf`
     * її не знає, тож `refuseTyped` пропускає її в дріт, а `PeerOutbox.isSpoken`
     * лишає в розмові. Це навмисно: відповідь моделі — сказане, а не вантаж.
     */
    const val MARK = "PH-AI:"

    /** Слова моделі з-під позначки. Веб читає це полем, а не тілом. */
    const val SAID = "ai_said"

    /**
     * Чиїм вузлом це пораховано — іменем, а не ідентифікатором.
     *
     * Поле складає МІСТ із `fromId` конверта, а не дріт. Дріт його не везе
     * свідомо: у конверті вже є засвідчений відправник, і друге, непідписане
     * імʼя поруч із ним можна було б підставити будь-яке.
     */
    const val VIA = "ai_via"

    /**
     * Як звертаються до моделі в групі.
     *
     * Кирилиця тут обовʼязкова: власник пише українською, і «@фантом» має
     * спрацювати так само, як «@phantom».
     */
    private val CALLED = listOf("phantom", "фантом", "ai", "ші", "шi")

    /**
     * Звертання починається з «@» і нічим іншим.
     *
     * Голе імʼя продукту не годиться: у розмові про PHANTOM слово «фантом»
     * трапляється щодня, і модель уривала б кожну другу репліку. «@» — те, що
     * людина вже вміє з будь-якого месенджера, і саме воно робить правило
     * «не згадав — мовчить» перевірним.
     *
     * `\b` тут не використано СВІДОМО: межа ASCII-слова не збігається перед
     * кирилицею, тож «@фантом» вона б не знайшла.
     */
    private val AT = Regex(
        "(^|[^\\p{L}\\p{N}_])@(" + CALLED.joinToString("|") + ")(?![\\p{L}\\p{N}_])",
        RegexOption.IGNORE_CASE,
    )

    fun mentioned(text: String): Boolean = AT.containsMatchIn(text)

    /**
     * Питання без звертання.
     *
     * «@phantom скільки це в кілометрах» питає про кілометри, а не про «@phantom».
     * Лишити звертання в запиті означало б віддати моделі рядок, половина якого
     * адресована їй самій.
     *
     * Порожнє питання — теж відповідь: коли в рядку не лишилось нічого, крім
     * звертання, повертається порожнє, і кликати модель нема з чим.
     */
    fun ask(text: String): String =
        AT.replace(text) { m -> m.groupValues[1] }.trim()

    fun encode(said: String): String = MARK + said

    fun isAi(body: String): Boolean = body.trimStart().startsWith(MARK)

    /** Слова моделі або null — це не її лист. */
    fun said(body: String): String? =
        body.trimStart().takeIf { it.startsWith(MARK) }?.removePrefix(MARK)
}
