package local.phantom.companion.self

/** Одна фраза PHANTOM: що сказати (рядок ресурсів) і чим його заповнити. */
data class Say(val line: Line, val args: List<Any> = emptyList()) {
    constructor(line: Line, vararg args: Any) : this(line, args.toList())
}

enum class Line {
    RAW, REMEMBERED, HEARD_NO_BRAIN, FORGOT, FORGOT_NOTHING, FORGOT_ALL, FORGOT_ALL_EMPTY,
    KNOWS_NOTHING, KNOWS_HEADER, KNOWS_FOOTER, KNOWS_OLD, NO_BRAIN,
    FROM_SELF, FROM_HEARD, FROM_GUESS,

    TUTOR_HELLO, TUTOR_Q_VARS, TUTOR_Q_LOOPS, TUTOR_RIGHT, TUTOR_WRONG,
    TUTOR_TASK_INTRO, TUTOR_SEND_CODE,
    TASK_VARS, TASK_COND, TASK_LOOPS, TASK_METHODS, TASK_ARRAYS,
    TUTOR_PASS, TUTOR_FAIL, TUTOR_RETRY, TUTOR_READ_NOT_RUN, TUTOR_SECOND_LOOK, TUTOR_TOMORROW, TUTOR_MORE,
    TUTOR_REVIEW, TUTOR_REVIEW_RIGHT, TUTOR_REVIEW_WRONG, TUTOR_NOTHING_TO_REVIEW, TUTOR_STOP,
    TUTOR_REMINDER, VISIT_WHY_LESSON, VISIT_WHY_REMINDER, VISIT_NOT_NOW, VISIT_DONT, VISIT_TITLE,

    ISSUE_BRACES, ISSUE_PARENS, ISSUE_SEMICOLON, ISSUE_QUOTES, ISSUE_NEED,

    TOPIC_VARS, TOPIC_COND, TOPIC_LOOPS, TOPIC_METHODS, TOPIC_ARRAYS,
    SKILL_OK, SKILL_SHAKY,

    COMMITMENT_SAVED, COMMITMENT_SAVED_DUE, COMMITMENT_CHOOSE,
    COMMITMENT_NONE, COMMITMENT_LIST_HEADER, COMMITMENT_MARKED_DONE, COMMITMENT_DONE_WHICH,
    WHEN_TODAY, WHEN_TOMORROW, WHEN_DAY_AFTER_TOMORROW,
    REMINDER_SET,
}
